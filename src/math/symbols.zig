/// Delimiter names usable after `\left`, `\right`, `\big` ... → glyph text.
pub fn delimiter(token: []const u8) ?[]const u8 {
    if (token.len == 1) {
        return switch (token[0]) {
            '(', ')', '[', ']', '|', '/', '<', '>' => switch (token[0]) {
                '<' => "⟨",
                '>' => "⟩",
                else => token,
            },
            '.' => "",
            else => null,
        };
    }
    const name = if (token[0] == '\\') token[1..] else token;
    if (std.mem.eql(u8, name, "{") or std.mem.eql(u8, name, "lbrace")) return "{";
    if (std.mem.eql(u8, name, "}") or std.mem.eql(u8, name, "rbrace")) return "}";
    if (std.mem.eql(u8, name, "|") or std.mem.eql(u8, name, "Vert") or std.mem.eql(u8, name, "lVert") or std.mem.eql(u8, name, "rVert")) return "‖";
    if (std.mem.eql(u8, name, "vert") or std.mem.eql(u8, name, "lvert") or std.mem.eql(u8, name, "rvert")) return "|";
    if (std.mem.eql(u8, name, "backslash")) return "\\";
    inline for (.{ "langle", "rangle", "lfloor", "rfloor", "lceil", "rceil", "lgroup", "rgroup", "uparrow", "downarrow", "updownarrow", "Uparrow", "Downarrow", "Updownarrow", "llbracket", "rrbracket" }) |n| {
        if (std.mem.eql(u8, name, n)) return lookup(n).?.text;
    }
    return null;
}

/// Class of a literal character in math mode.
pub fn charClass(cp: u21) Class {
    return switch (cp) {
        '+', '-', '*', 0x2212, 0x00B1, 0x00D7, 0x00F7, 0x22C5, 0x2218, 0x2219 => .bin,
        '=', '<', '>', ':', 0x2264, 0x2265, 0x2260, 0x2248, 0x2261, 0x223C, 0x2208, 0x2209, 0x2282, 0x2283, 0x2286, 0x2287, 0x2192, 0x2190, 0x21D2, 0x21D4 => .rel,
        '(', '[', 0x27E8 => .open,
        ')', ']', '!', '?', 0x27E9 => .close,
        ',', ';' => .punct,
        else => .ord,
    };
}
