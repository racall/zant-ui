//! Visual tokens for rendered Markdown (Streamdown's typography classes and
//! shadcn-style CSS variables), with light and dark presets. Code colours
//! follow Streamdown's default Shiki themes: github-light / github-dark.
const text_mod = @import("../renderer/text.zig");

pub const CodeColors = struct {
    plain: u32,
    keyword: u32,
    string: u32,
    comment: u32,
    number: u32,
    function: u32,
    type: u32,
    constant: u32,
    property: u32,
    tag: u32,
    attribute: u32,
    punctuation: u32,
    meta: u32,
    inserted: u32,
    inserted_bg: u32,
    deleted: u32,
    deleted_bg: u32,
};

pub const Theme = struct {
    dark: bool = false,
    background: u32,
    foreground: u32,
    muted: u32,
    muted_foreground: u32,
    border: u32,
    heading: u32,
    link: u32,
    link_blocked: u32,
    inline_code_bg: u32,
    inline_code_fg: u32,
    code_bg: u32,
    code_header_bg: u32,
    code_border: u32,
    line_number: u32,
    quote_bar: u32,
    quote_text: u32,
    table_header_bg: u32,
    table_border: u32,
    highlight_bg: u32,
    marker: u32,
    caret: u32,
    button_fg: u32,
    overlay: u32,
    surface: u32,
    note: u32,
    tip: u32,
    important: u32,
    warning: u32,
    caution: u32,
    math: u32,
    math_error: u32,
    code: CodeColors,

    body_family: text_mod.Family = .sans,
    heading_family: text_mod.Family = .sans,
    heading_weight: text_mod.Weight = .semibold,
    /// Heading sizes relative to the body size (h1..h6).
    heading_scale: [6]f32 = .{ 1.875, 1.5, 1.25, 1.125, 1.0, 0.875 },
    /// Gap between top-level blocks, relative to the body size.
    block_gap: f32 = 1.0,
    line_height: f32 = 1.75,
};

