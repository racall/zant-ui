//! The editor's type files next to an app: `zant.d.ts` (the framework's
//! TSX surface) and `zant.i18n.d.ts` (the app's message keys and locales,
//! from `locales/*.json`). Both are generated, so `zant run` / `build` /
//! `sync` keep them current; the build itself only writes to `OUT_DIR`.

use std::path::Path;

/// The marker `zant-tsx-dts` writes on the first line of `zant.d.ts`.
const FRAMEWORK_MARKER: &str = "// Generated by `zant-tsx-dts`";

/// Refreshes both files when their content is out of date. Errors in
/// `locales/` are left to the build, which reports them with locations.
pub fn sync(root: &str) {
    let root = Path::new(root);
    if let Ok(Some(text)) = zant_build::i18n::declarations(root) {
        write_if_changed(&root.join("zant.i18n.d.ts"), &text);
    }
    refresh_framework(root);
}

/// `zant.d.ts` follows the framework the project builds with: the
/// installed one when the project depends on its tag (or on a local path).
fn refresh_framework(root: &Path) {
    let current = root.join("zant.d.ts");
    let Ok(existing) = std::fs::read_to_string(&current) else {
        return;
    };
    if !existing.starts_with(FRAMEWORK_MARKER) {
        return; // edited by hand or not ours
    }
    let manifest = std::fs::read_to_string(root.join("Cargo.toml")).unwrap_or_default();
    let matches = match crate::framework::project_tag(&manifest) {
        Some(tag) => tag == crate::framework::installed_tag(),
        None => true, // a path dependency: the checkout this CLI belongs to
    };
    if !matches {
        return;
    }
    let source = crate::zant_root().join("crates/zant-tsx/zant.d.ts");
    if let Ok(text) = std::fs::read_to_string(source) {
        write_if_changed(&current, &text);
    }
}

fn write_if_changed(path: &Path, text: &str) {
    if std::fs::read_to_string(path).is_ok_and(|old| old == text) {
        return;
    }
    if let Err(error) = std::fs::write(path, text) {
        crate::dim_line(&format!("cannot update {}: {error}", path.display()));
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn app_declarations_follow_the_catalogs() {
        let root = std::env::temp_dir().join(format!("zant-declarations-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(root.join("locales")).unwrap();
        std::fs::write(root.join("locales/en.json"), r#"{"hi": "Hi {name}"}"#).unwrap();
        sync(root.to_str().unwrap());
        let text = std::fs::read_to_string(root.join("zant.i18n.d.ts")).unwrap();
        assert!(
            text.contains(r#""hi": { name: string | number };"#),
            "{text}"
        );
        // a hand-written zant.d.ts is left alone
        std::fs::write(root.join("zant.d.ts"), "// mine\n").unwrap();
        sync(root.to_str().unwrap());
        assert_eq!(
            std::fs::read_to_string(root.join("zant.d.ts")).unwrap(),
            "// mine\n"
        );
        std::fs::remove_dir_all(root).unwrap();
    }
}
