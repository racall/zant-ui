//! The hidden crate `zant run` builds the app's UI library from.
//!
//! The app itself is a normal binary crate. For hot reload the same sources
//! (its TSX, its `native/` modules, its dependencies) are compiled a second
//! time as a dynamic library, from a crate the CLI writes under
//! `target/zant-hot/crate/`: the app's dependencies with absolute paths, a
//! build script that runs the TSX compiler on the app, and a one-line
//! `lib.rs` (`zant::hot_app!()`). The developer never sees it.

use std::path::{Path, PathBuf};

/// Where the hot-reload pieces of one app live.
pub struct Paths {
    /// `<app>/target/zant-hot/crate`: the generated crate.
    pub crate_dir: PathBuf,
    /// Its cargo target directory.
    pub target_dir: PathBuf,
    /// Numbered copies of each built library (a loaded library file is
    /// locked on Windows and cached by path on macOS).
    pub gen_dir: PathBuf,
    /// `<zant>/target/zant-hot`: the host and the shared native library,
    /// built once per Zant UI checkout.
    pub zant_dir: PathBuf,
}

impl Paths {
    pub fn new(root: &str, zant_root: &Path) -> Paths {
        let work = Path::new(root).join("target").join("zant-hot");
        Paths {
            crate_dir: work.join("crate"),
            target_dir: work.join("target"),
            gen_dir: work.join("gen"),
            zant_dir: zant_root.join("target").join("zant-hot"),
        }
    }

    /// `ZANT_NATIVE_SHARED`: the shared native library's directory.
    pub fn native_dir(&self) -> PathBuf {
        self.zant_dir.join("native")
    }

    pub fn host_exe(&self) -> PathBuf {
        let name = if cfg!(windows) {
            "zant-hot-host.exe"
        } else {
            "zant-hot-host"
        };
        self.zant_dir.join("debug").join(name)
    }

    /// The library cargo writes.
    pub fn built_library(&self, release: bool) -> PathBuf {
        let profile = if release { "release" } else { "debug" };
        self.target_dir
            .join(profile)
            .join(library_file("zant_hot_ui"))
    }

    /// Rust dylibs used by all numbered UI generations.
    pub fn deps_dir(&self, release: bool) -> PathBuf {
        self.target_dir
            .join(if release { "release" } else { "debug" })
            .join("deps")
    }
}

/// `libname.dylib` / `name.dll`.
pub fn library_file(name: &str) -> String {
    if cfg!(windows) {
        format!("{name}.dll")
    } else {
        format!("lib{name}.dylib")
    }
}

/// Writes (or refreshes) the generated crate for the app at `root`.
pub fn write(root: &str, zant_root: &Path, paths: &Paths) -> Result<(), String> {
    let root_path = Path::new(root);
    let manifest = root_path.join("Cargo.toml");
    let text = std::fs::read_to_string(&manifest)
        .map_err(|error| format!("{}: {error}", manifest.display()))?;
    let app: toml::Table = text
        .parse()
        .map_err(|error| format!("{}: {error}", manifest.display()))?;
    let app = super::workspace::resolve(app, root_path)?;
    std::fs::create_dir_all(&paths.crate_dir).map_err(|error| error.to_string())?;

    write_if_changed(
        &paths.crate_dir.join("Cargo.toml"),
        &manifest_text(&app, root_path, zant_root),
    )?;
    write_if_changed(
        &paths.crate_dir.join("lib.rs"),
        "// Generated by `zant run` (hot reload) — do not edit.\nzant::hot_app!();\n",
    )?;
    write_if_changed(&paths.crate_dir.join("build.rs"), &build_script(root_path))?;
    // the app's lock file keeps the dependency versions the app builds with
    let lock = root_path.join("Cargo.lock");
    let hot_lock = paths.crate_dir.join("Cargo.lock");
    if lock.is_file() {
        let _ = std::fs::copy(&lock, &hot_lock);
    }
    Ok(())
}

fn write_if_changed(path: &Path, content: &str) -> Result<(), String> {
    if std::fs::read_to_string(path).is_ok_and(|old| old == content) {
        return Ok(());
    }
    std::fs::write(path, content).map_err(|error| format!("{}: {error}", path.display()))
}

/// The generated crate's Cargo.toml: the app's dependencies (relative paths
/// made absolute) plus zant-build for the build script.
fn manifest_text(app: &toml::Table, root: &Path, zant_root: &Path) -> String {
    let package = app.get("package").and_then(toml::Value::as_table);
    let name = package
        .and_then(|package| package.get("name"))
        .and_then(toml::Value::as_str)
        .unwrap_or("app");
    let edition = package
        .and_then(|package| package.get("edition"))
        .and_then(toml::Value::as_str)
        .unwrap_or("2024");

    let mut out = toml::Table::new();
    let mut new_package = toml::Table::new();
    new_package.insert("name".into(), format!("{name}-hot").into());
    new_package.insert("version".into(), "0.0.0".into());
    new_package.insert("edition".into(), edition.into());
    new_package.insert("publish".into(), false.into());
    new_package.insert("build".into(), "build.rs".into());
    out.insert("package".into(), new_package.into());

    let mut lib = toml::Table::new();
    lib.insert("name".into(), "zant_hot_ui".into());
    lib.insert("path".into(), "lib.rs".into());
    lib.insert(
        "crate-type".into(),
        toml::Value::Array(vec!["dylib".into()]),
    );
    out.insert("lib".into(), lib.into());

    if let Some(deps) = app.get("dependencies").and_then(toml::Value::as_table) {
        out.insert("dependencies".into(), absolute_paths(deps, root).into());
    }
    let deps = out
        .entry("dependencies")
        .or_insert_with(|| toml::Table::new().into())
        .as_table_mut()
        .expect("dependencies");
    deps.insert("zant".into(), framework_dependency(zant_root));
    if let Some(targets) = app.get("target").and_then(toml::Value::as_table) {
        let mut new_targets = toml::Table::new();
        for (cfg, table) in targets {
            let Some(deps) = table
                .as_table()
                .and_then(|table| table.get("dependencies"))
                .and_then(toml::Value::as_table)
            else {
                continue;
            };
            let mut entry = toml::Table::new();
            let mut deps = absolute_paths(deps, root);
            if deps.contains_key("zant") {
                deps.insert("zant".into(), framework_dependency(zant_root));
            }
            entry.insert("dependencies".into(), deps.into());
            new_targets.insert(cfg.clone(), entry.into());
        }
        if !new_targets.is_empty() {
            out.insert("target".into(), new_targets.into());
        }
    }

    let mut build_deps = toml::Table::new();
    let mut zant_build = toml::Table::new();
    zant_build.insert(
        "path".into(),
        path_text(&zant_root.join("crates").join("zant-build")).into(),
    );
    build_deps.insert("zant-build".into(), zant_build.into());
    out.insert("build-dependencies".into(), build_deps.into());

    if let Some(profile) = app.get("profile") {
        out.insert("profile".into(), profile.clone());
    }
    // Keep framework/dependency profiles unchanged across app edits. Only the
    // replaceable UI crate needs reduced debug information for the edit loop.
    let profiles = out
        .entry("profile")
        .or_insert_with(|| toml::Table::new().into())
        .as_table_mut()
        .expect("profiles");
    let dev = profiles
        .entry("dev")
        .or_insert_with(|| toml::Table::new().into())
        .as_table_mut()
        .expect("dev profile");
    let packages = dev
        .entry("package")
        .or_insert_with(|| toml::Table::new().into())
        .as_table_mut()
        .expect("package profiles");
    let ui = packages
        .entry(format!("{name}-hot"))
        .or_insert_with(|| toml::Table::new().into())
        .as_table_mut()
        .expect("UI profile");
    ui.entry("debug").or_insert(1.into());
    if cfg!(target_os = "macos") {
        ui.entry("split-debuginfo").or_insert("unpacked".into());
    }
    out.insert("workspace".into(), toml::Table::new().into());
    format!(
        "# Generated by `zant run` (hot reload) from the app's Cargo.toml — do not edit.\n{}",
        toml::to_string(&out).unwrap_or_default()
    )
}

fn framework_dependency(zant_root: &Path) -> toml::Value {
    toml::Table::from_iter([
        ("package".into(), "zant-dylib".into()),
        (
            "path".into(),
            path_text(&zant_root.join("crates/zant-dylib")).into(),
        ),
    ])
    .into()
}

/// `deps` with every relative `path = "…"` resolved against the app root.
fn absolute_paths(deps: &toml::Table, root: &Path) -> toml::Table {
    let mut out = deps.clone();
    for (_, value) in out.iter_mut() {
        let Some(table) = value.as_table_mut() else {
            continue;
        };
        let Some(path) = table.get("path").and_then(toml::Value::as_str) else {
            continue;
        };
        let path = Path::new(path);
        if path.is_relative() {
            let joined = root.join(path);
            let resolved = joined.canonicalize().unwrap_or(joined);
            table.insert("path".into(), path_text(&resolved).into());
        }
    }
    out
}

/// A path for TOML / Rust source: forward slashes, no `\\?\` prefix.
fn path_text(path: &Path) -> String {
    let text = path.to_string_lossy().replace('\\', "/");
    text.strip_prefix("//?/").map(str::to_owned).unwrap_or(text)
}

/// The generated build script: the TSX compiler over the app's sources.
fn build_script(root: &Path) -> String {
    let resolved = root.canonicalize().unwrap_or_else(|_| PathBuf::from(root));
    let root = path_text(&resolved);
    include_str!("build.rs.template").replace("__APP_ROOT__", &format!("{root:?}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_manifest_keeps_dependencies_and_makes_paths_absolute() {
        let app: toml::Table = r#"
[package]
name = "demo"
edition = "2024"
build = "native/build.rs"

[dependencies]
zant = { path = "../zant/crates/zant" }
serde = "1"
helper = { path = "native/helper" }

[target.'cfg(windows)'.dependencies]
winreg = "0.5"
zant = { path = "../zant/crates/zant" }
"#
        .parse()
        .expect("toml");
        let text = manifest_text(&app, Path::new("/work/app"), Path::new("/zant"));
        let parsed: toml::Table = text.parse().expect("generated toml");
        assert_eq!(parsed["package"]["name"].as_str(), Some("demo-hot"));
        assert_eq!(parsed["package"]["build"].as_str(), Some("build.rs"));
        assert_eq!(parsed["lib"]["crate-type"][0].as_str(), Some("dylib"));
        assert_eq!(parsed["dependencies"]["serde"].as_str(), Some("1"));
        assert_eq!(
            parsed["dependencies"]["helper"]["path"].as_str(),
            Some("/work/app/native/helper")
        );
        assert_eq!(
            parsed["dependencies"]["zant"]["path"].as_str(),
            Some("/zant/crates/zant-dylib")
        );
        assert_eq!(
            parsed["dependencies"]["zant"]["package"].as_str(),
            Some("zant-dylib")
        );
        assert!(parsed["target"]["cfg(windows)"]["dependencies"]["winreg"].is_str());
        assert_eq!(
            parsed["target"]["cfg(windows)"]["dependencies"]["zant"],
            parsed["dependencies"]["zant"]
        );
        assert_eq!(
            parsed["build-dependencies"]["zant-build"]["path"].as_str(),
            Some("/zant/crates/zant-build")
        );
        assert!(parsed["workspace"].is_table());
        assert_eq!(
            parsed["profile"]["dev"]["package"]["demo-hot"]["debug"].as_integer(),
            Some(1)
        );
        assert!(parsed["profile"]["dev"].get("debug").is_none());
    }

    #[test]
    fn library_names_follow_the_platform() {
        if cfg!(windows) {
            assert_eq!(library_file("x"), "x.dll");
        } else {
            assert_eq!(library_file("x"), "libx.dylib");
        }
    }
}
