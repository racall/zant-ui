//! Port of `tools/zant/scaffold.zig`: copy a language template, substituting
//! project metadata only in text files.

use crate::project::Language;
use std::path::Path;

/// The template `zant create` copies for a Zig project. WP-6.3 removes this
/// pure-Zig template and keeps only the TS one; until then create keeps both
/// languages selectable.
pub const TEMPLATE_ZIG: &str = "scaffold/template";

/// The TSX template. It is still the Zig-build template in this worktree
/// (build.zig + native/*.zig); WP-6.3 replaces it with a Cargo.toml + build.rs
/// template, so this path constant is the only thing `create` needs to change.
pub const TEMPLATE_TS: &str = "scaffold/template-ts";

/// The template directory of a language (the constant a later WP updates).
pub fn template_dir(language: Language) -> &'static str {
    match language {
        Language::Zig => TEMPLATE_ZIG,
        Language::Ts => TEMPLATE_TS,
    }
}

pub struct Options {
    pub framework: String,
    pub target: String,
    pub language: Language,
    pub title: String,
    pub bundle: String,
    pub zig_name: String,
    pub dependency: String,
    pub hidden_titlebar: bool,
}

pub fn write(options: &Options) -> std::io::Result<()> {
    let source = Path::new(&options.framework).join(template_dir(options.language));
    copy_tree(&source, Path::new(&options.target), options, true)?;
    // Both languages ship the same editable icons and design rules.
    if options.language == Language::Ts {
        let icons = Path::new(&options.framework).join("scaffold/template/assets");
        let assets = Path::new(&options.target).join("assets");
        copy_tree(&icons, &assets, options, false)?;
        let design = Path::new(&options.framework).join("scaffold/template/DESIGN.md");
        let dest = Path::new(&options.target).join("DESIGN.md");
        let data = crate::read_file(&design)?;
        crate::write_file(&dest, &data)?;
        let types = Path::new(&options.framework).join("tools/tsx/zant.d.ts");
        let dest_types = Path::new(&options.target).join("zant.d.ts");
        let declarations = crate::read_file(&types)?;
        crate::write_file(&dest_types, &declarations)?;
    } else {
        let ignore = Path::new(&options.target).join(".gitignore");
        crate::write_file(
            &ignore,
            b"# build output and caches\nzig-out*/\ntarget/\n.zig-cache/\n# Zant UI link for projects on another drive (Windows)\n.zant/\n# generated by `zant` on macOS from app.config.json\nInfo.plist\napp.entitlements\n",
        )?;
    }
    Ok(())
}

fn copy_tree(
    source: &Path,
    dest: &Path,
    options: &Options,
    substitute: bool,
) -> std::io::Result<()> {
    std::fs::create_dir_all(dest)?;
    for entry in std::fs::read_dir(source)? {
        let entry = entry?;
        let name = entry.file_name();
        let name = name.to_string_lossy();
        // app.config.json is written by create after validating all options.
        if name == "app.config.json" {
            continue;
        }
        let from = source.join(&*name);
        let to = dest.join(&*name);
        let file_type = entry.file_type()?;
        if file_type.is_dir() {
            let text = substitute && name != "assets";
            copy_tree(&from, &to, options, text)?;
        } else if file_type.is_file() {
            let data = crate::read_file(&from)?;
            let output = if substitute {
                expand(
                    &String::from_utf8_lossy(&data),
                    options,
                    name.ends_with(".tsx"),
                )
            } else {
                data
            };
            crate::write_file(&to, &output)?;
        }
    }
    Ok(())
}

fn expand(source: &str, options: &Options, is_tsx: bool) -> Vec<u8> {
    let fingerprint = (u64::from(crc32(options.zig_name.as_bytes())) << 32) | 0x9e37_79b9;
    let hex = format!("0x{fingerprint:016x}");
    let top = if options.hidden_titlebar {
        "top: 56"
    } else {
        "top: 24"
    };
    let pairs: [(&str, &str); 7] = [
        ("__APP_NAME_SNAKE__", &options.zig_name),
        ("__APP_FINGERPRINT__", &hex),
        ("__ZANT_PATH__", &options.dependency),
        ("__APP_TITLE__", &options.title),
        ("__BUNDLE_ID__", &options.bundle),
        ("top: 24 /* titlebar */", top),
        (
            "__TOP_PADDING__",
            if options.hidden_titlebar { "56" } else { "24" },
        ),
    ];
    let mut output = source.to_string();
    for (needle, value) in pairs {
        // Titles in source must be escaped as string literals, unlike Markdown.
        let value = if is_tsx && needle == "__APP_TITLE__" {
            crate::escape_json(value)
        } else {
            value.to_string()
        };
        output = output.replace(needle, &value);
    }
    output.into_bytes()
}

/// `std.hash.Crc32` (IEEE) of the Zig name, used for the project fingerprint.
fn crc32(data: &[u8]) -> u32 {
    let mut crc = 0xffff_ffffu32;
    for byte in data {
        crc ^= u32::from(*byte);
        for _ in 0..8 {
            let mask = (crc & 1).wrapping_neg();
            crc = (crc >> 1) ^ (0xedb8_8320 & mask);
        }
    }
    !crc
}

#[cfg(test)]
mod tests {
    use super::*;

    fn repo_root() -> String {
        std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../..")
            .canonicalize()
            .expect("repo root")
            .to_string_lossy()
            .into_owned()
    }

    fn temp_dir(name: &str) -> std::path::PathBuf {
        let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../..")
            .join("target/zant-cli-test")
            .join(name);
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).expect("temp dir");
        dir
    }

    fn options(target: &std::path::Path, language: Language) -> Options {
        Options {
            framework: repo_root(),
            target: target.to_string_lossy().into_owned(),
            language,
            title: "My \"App\"".to_string(),
            bundle: "com.acme.myapp".to_string(),
            zig_name: "my_app".to_string(),
            dependency: "../zant-ui".to_string(),
            hidden_titlebar: true,
        }
    }

    #[test]
    fn template_directories_are_constants() {
        assert_eq!(template_dir(Language::Zig), TEMPLATE_ZIG);
        assert_eq!(template_dir(Language::Ts), TEMPLATE_TS);
        assert!(Path::new(&repo_root()).join(TEMPLATE_ZIG).is_dir());
        assert!(Path::new(&repo_root()).join(TEMPLATE_TS).is_dir());
    }

    #[test]
    fn copies_the_zig_template_and_substitutes_metadata() {
        let dir = temp_dir("scaffold-zig");
        let target = dir.join("my-app");
        write(&options(&target, Language::Zig)).expect("scaffold");
        assert!(target.join("src/main.zig").is_file());
        assert!(target.join("src/components/dashboard.zig").is_file());
        assert!(target.join("build.zig").is_file());
        assert!(target.join("assets/icons/app-macos.png").is_file());
        // app.config.json is written by create, not copied from the template
        assert!(!target.join("app.config.json").exists());
        assert!(target.join(".gitignore").is_file());
        let zon = std::fs::read_to_string(target.join("build.zig.zon")).expect("zon");
        assert!(zon.contains(".name = .my_app"), "{zon}");
        assert!(zon.contains(".path = \"../zant-ui\""), "{zon}");
        assert!(zon.contains("0x"), "{zon}");
        let readme = std::fs::read_to_string(target.join("README.md")).expect("readme");
        assert!(readme.contains("com.acme.myapp"), "{readme}");
        assert!(readme.contains("My \"App\""), "{readme}");
        let main = std::fs::read_to_string(target.join("src/main.zig")).expect("main");
        assert!(main.contains(".top = 56"), "{main}");
        // Only substitutes in text files, not in the binary icon assets.
        let icon = std::fs::read(target.join("assets/icons/app-macos.png")).expect("icon");
        let original = std::fs::read(
            Path::new(&repo_root()).join("scaffold/template/assets/icons/app-macos.png"),
        )
        .expect("original icon");
        assert_eq!(icon, original);
    }

    #[test]
    fn copies_the_ts_template_with_shared_assets_and_types() {
        let dir = temp_dir("scaffold-ts");
        let target = dir.join("my-ts-app");
        write(&options(&target, Language::Ts)).expect("scaffold");
        assert!(target.join("src/App.tsx").is_file());
        assert!(target.join("zant.d.ts").is_file());
        assert!(target.join("DESIGN.md").is_file());
        assert!(target.join("assets/icons/app-windows.png").is_file());
        assert!(!target.join("app.config.json").exists());
        // TSX string literals get JSON-escaped titles.
        let app = std::fs::read_to_string(target.join("src/App.tsx")).expect("App.tsx");
        assert!(app.contains("My \\\"App\\\""), "{app}");
    }
}
