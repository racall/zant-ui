//! Native modules of a TS + TSX app: the runtime side of the `native/` bridge
//! (port of `src/tsx_native.zig`; the codegen side lands in WP-5.8).
//!
//! Zig checked each `native/<name>.zig` against its spec (`native/<name>.ts`)
//! at compile time: every function the spec declares had to exist as a `pub fn`
//! with exactly that signature. Rust's type system does the checking
//! statically instead (WP-5.8 generates one trait per spec from the `.ts`
//! file; the app writes `impl ClipSpec for Native` and a missing or mistyped
//! function is a rustc error at the `impl`), so the primary path is:
//!
//! ```ignore
//! // native/lib.rs (generated by zant-tsx, WP-5.8)
//! pub mod clip;
//! pub use clip::Native;
//!
//! // generated call site of `invoke.list()`
//! <crate::native::clip::Native as crate::native::spec::ClipSpec>::list()
//! ```
//!
//! What is left for the runtime is the **registry** the generated entry uses
//! when a module is resolved by name (the `invoke` namespace, tests that swap
//! an implementation, and native modules registered by the app instead of
//! generated): implementations register themselves by module name and are
//! fetched with a type check. The trait below is that interface.
//!
//! ```ignore
//! impl tsx::native::NativeModule for Native {
//!     const NAME: &'static str = "clip";
//! }
//! tsx::native::register::<Native>(Native);
//! let native = tsx::native::get::<Native>("clip").expect("registered");
//! ```
//!
//! Unlike the Zig compile-time check this registry is optional overhead: the
//! static call path (the generated one) never touches it.

use std::any::Any;
use std::cell::RefCell;
use std::collections::HashMap;
use std::rc::Rc;

/// A native module implementation (`native/<name>.rs`): the module name is the
/// `.ts` spec's file stem.
pub trait NativeModule: 'static {
    /// `native/<NAME>.ts` / `native/<NAME>.rs`.
    const NAME: &'static str;
}

thread_local! {
    /// Registered implementations of this UI thread, by module name.
    static MODULES: RefCell<HashMap<&'static str, Rc<dyn Any>>> =
        RefCell::new(HashMap::new());
}

/// Registers `module` under its [`NativeModule::NAME`]; false when that name
/// is already taken (the first registration wins, like one module per spec).
pub fn register<T: NativeModule>(module: T) -> bool {
    MODULES.with(|modules| {
        let mut modules = modules.borrow_mut();
        if modules.contains_key(T::NAME) {
            return false;
        }
        let value: Rc<dyn Any> = Rc::new(module);
        modules.insert(T::NAME, value);
        true
    })
}

/// The registered implementation of `name`, downcast to `T`; `None` when the
/// name is unknown or holds another type.
pub fn get<T: 'static>(name: &str) -> Option<Rc<T>> {
    MODULES.with(|modules| {
        let modules = modules.borrow();
        let value = modules.get(name)?;
        Rc::clone(value).downcast::<T>().ok()
    })
}

/// Whether a module is registered under `name`.
pub fn registered(name: &str) -> bool {
    MODULES.with(|modules| modules.borrow().contains_key(name))
}

/// Forgets every registration (tests, or an app restart in the same process).
pub fn clear() {
    MODULES.with(|modules| modules.borrow_mut().clear());
}

#[cfg(test)]
mod tests {
    use super::*;

    trait Doubler: 'static {
        fn twice(&self, n: i64) -> i64;
    }

    struct Demo {
        base: i64,
    }

    impl NativeModule for Demo {
        const NAME: &'static str = "demo";
    }

    impl Doubler for Demo {
        fn twice(&self, n: i64) -> i64 {
            self.base + n * 2
        }
    }

    #[test]
    fn a_registered_module_is_fetched_by_name_with_its_type() {
        clear();
        assert!(!registered("demo"));
        assert!(register(Demo { base: 0 }));
        assert!(registered("demo"));
        assert!(!register(Demo { base: 1 }), "the first registration wins");
        let module = get::<Demo>("demo").expect("registered");
        assert_eq!(module.twice(2), 4);
        // the same object through the trait object of its spec
        let as_trait: Rc<dyn Doubler> = module;
        assert_eq!(as_trait.twice(3), 6);
        assert!(get::<String>("demo").is_none(), "wrong type: None");
        assert!(get::<Demo>("missing").is_none());
        clear();
        assert!(get::<Demo>("demo").is_none());
    }
}
