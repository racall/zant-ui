//! Shared helpers and unit tests for `zant-build`'s internals (the end-to-end
//! build-script tests live in `tests/build.rs`).

use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicUsize, Ordering};

use crate::compile::SourceFile;

/// The fixture app (`tests/fixtures/tsx-app`).
pub(crate) fn fixture_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/tsx-app")
}

/// A fresh, empty directory under the system temp dir.
pub(crate) fn temp_dir(prefix: &str) -> PathBuf {
    static COUNTER: AtomicUsize = AtomicUsize::new(0);
    let index = COUNTER.fetch_add(1, Ordering::Relaxed);
    let path = std::env::temp_dir().join(format!(
        "zant-build-{prefix}-{}-{index}",
        std::process::id()
    ));
    let _ = std::fs::remove_dir_all(&path);
    std::fs::create_dir_all(&path).expect("temp dir");
    path
}

// ── the generated entry (`OUT_DIR/main.rs`) ────────────────────────────

#[test]
fn the_entry_declares_every_tsx_module_and_skips_rust() {
    let files = [
        SourceFile::tsx("src/App.tsx", ""),
        SourceFile::tsx("src/components/TodoRow.tsx", ""),
        SourceFile::rust("src/main.rs", ""),
        SourceFile::native_spec("native/clips.ts", ""),
    ];
    let entry = crate::module_declarations(&files);
    assert_eq!(
        entry,
        "// Generated by zant-build from the app's TSX sources. Do not edit.\n\
         //\n\
         // `src/main.rs` includes this file at the crate root:\n\
         //     include!(concat!(env!(\"OUT_DIR\"), \"/main.rs\"));\n\
         // `#[path]` is resolved relative to this file's directory (OUT_DIR).\n\
         #[path = \"App.rs\"]\npub mod app;\n\
         #[path = \"TodoRow.rs\"]\npub mod todo_row;\n"
    );
    // `include!` rejects inner attributes and inner doc comments.
    assert!(!entry.contains("#!"));
    assert!(!entry.contains("//!"));
}

// ── the root component check (`src/App.tsx`) ───────────────────────────

#[test]
fn the_root_component_must_be_a_default_export_without_props() {
    let path = Path::new("src/App.tsx");
    assert_eq!(
        crate::validate_root(path, "export function App() { return <View/>; }")
            .unwrap_err()
            .to_string(),
        "`src/App.tsx` has no default exported component; the app's root is \
         `export default function App() { … }`"
    );
    assert_eq!(
        crate::validate_root(
            path,
            "export default function App(props: { x: u32 }) { return <View/>; }"
        )
        .unwrap_err()
        .to_string(),
        "the root component of `src/App.tsx` takes no props (it is the app's state)"
    );
    crate::validate_root(path, "export default function App() { return <View/>; }").expect("root");
    // A syntax error is reported by the compiler with a rendered diagnostic.
    crate::validate_root(path, "const x = ;").expect("syntax errors are the compiler's");
}

// ── icons ─────────────────────────────────────────────────────────────

#[test]
fn the_icon_module_is_written_with_relative_include_paths() {
    let root = fixture_root();
    let out = temp_dir("icons");
    let icons = crate::app_icons(&root).expect("enumerate");
    let (module, copies) = crate::icons::write(&out, &icons).expect("write");
    assert_eq!(module, out.join("icons.rs"));
    assert_eq!(copies.len(), icons.len());
    for (icon, copy) in icons.iter().zip(copies.iter()) {
        assert!(copy.is_file(), "{}", copy.display());
        assert_eq!(copy.file_name().unwrap(), icon.file_name().as_str());
    }
    let source = std::fs::read_to_string(&module).expect("module");
    assert!(source.contains("include_bytes!(\"_icons/tray-dark.png\")"));
    let _ = std::fs::remove_dir_all(&out);
}

// ── the Windows `.ico` ────────────────────────────────────────────────

#[test]
fn the_windows_icon_is_built_from_the_256px_png() {
    let root = fixture_root();
    let ico = crate::windows_icon(&root).expect("ico").expect("icon");
    // ICONDIR: reserved 0, type 1, 8 images.
    assert_eq!(&ico[0..4], &[0, 0, 1, 0]);
    assert_eq!(u16::from_le_bytes([ico[4], ico[5]]), 8);
    // First entry: 16×16, one plane, 32 bpp.
    assert_eq!((ico[6], ico[7]), (16, 16));
    assert_eq!(u16::from_le_bytes([ico[10], ico[11]]), 1);
    assert_eq!(u16::from_le_bytes([ico[12], ico[13]]), 32);
    let no_icon = temp_dir("no-icon");
    assert_eq!(crate::windows_icon(&no_icon).expect("none"), None);
    let _ = std::fs::remove_dir_all(&no_icon);
}

#[test]
fn a_non_square_windows_icon_is_an_error() {
    let root = temp_dir("bad-icon");
    std::fs::create_dir_all(root.join("assets/icons")).expect("dirs");
    // A valid 16×16 PNG where a ≥256×256 icon is required.
    let image = crate::png::Image {
        width: 16,
        height: 16,
        rgba: vec![0; 16 * 16 * 4],
    };
    let encoded = crate::png::encode(&image).expect("png");
    std::fs::write(root.join("assets/icons/app-windows.png"), encoded).expect("write");
    let error = crate::windows_icon(&root).expect_err("error");
    assert!(
        error
            .to_string()
            .contains("must be square and at least 256×256"),
        "{error}"
    );
    let _ = std::fs::remove_dir_all(&root);
}
