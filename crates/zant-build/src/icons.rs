//! `assets/icons/*.png` as `icon_<name>` byte constants (Zig `addAppIcons`).
//!
//! The Zig build added one anonymous import per PNG, so app code could write
//! `@embedFile("icon_tray_dark")`; `-` in the file stem becomes `_`. Rust has
//! no module-level anonymous imports, so the same mapping is written as a
//! generated `icons.rs` next to the compiled modules:
//!
//! ```rust,ignore
//! // src/main.rs (or a native module)
//! mod icons {
//!     include!(concat!(env!("OUT_DIR"), "/icons.rs"));
//! }
//!
//! const TRAY_DARK: &[u8] = icons::icon_tray_dark;
//! ```
//!
//! The PNGs are copied to `$OUT_DIR/_icons/<file>.png` first, so the
//! `include_bytes!` paths are relative to `icons.rs` and do not repeat the
//! project's absolute path.
//!
//! Every icon is also listed in `ICONS` (`[("<stem>", bytes)]`) for lookups by
//! name.

use std::path::{Path, PathBuf};

use crate::Error;

/// One PNG of `assets/icons/` (Zig's `app_icons` table plus the app's own).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Icon {
    /// The Rust identifier (`tray-dark.png` → `icon_tray_dark`).
    pub name: String,
    /// The file stem without `.png` (`tray-dark`).
    pub stem: String,
    /// The PNG on disk.
    pub path: PathBuf,
}

impl Icon {
    /// The file name in `assets/icons/` (`tray-dark.png`).
    pub fn file_name(&self) -> String {
        self.stem.clone() + ".png"
    }
}

/// Every PNG in `assets/icons/` (`-` → `_`, sorted by identifier), like Zig's
/// `addAppIcons`. A missing directory means no icons, not an error.
pub fn enumerate(app_root: &Path) -> Result<Vec<Icon>, Error> {
    let directory = app_root.join("assets/icons");
    let entries = match std::fs::read_dir(&directory) {
        Ok(entries) => entries,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(Vec::new()),
        Err(error) => return Err(Error::Io(error)),
    };
    let mut icons = Vec::new();
    for entry in entries {
        let entry = entry?;
        if !entry.file_type()?.is_file() {
            continue;
        }
        let Some(file_name) = entry.file_name().to_str().map(str::to_owned) else {
            continue;
        };
        let Some(stem) = file_name.strip_suffix(".png") else {
            continue;
        };
        icons.push(Icon {
            name: format!("icon_{}", stem.replace('-', "_")),
            stem: stem.to_owned(),
            path: entry.path(),
        });
    }
    icons.sort_by(|left, right| left.name.cmp(&right.name));
    Ok(icons)
}

/// Writes `$OUT_DIR/_icons/<file>.png` for every icon and returns the
/// `icons.rs` module plus the copied files.
pub fn write(out_dir: &Path, icons: &[Icon]) -> Result<(PathBuf, Vec<PathBuf>), Error> {
    let directory = out_dir.join("_icons");
    if !icons.is_empty() {
        std::fs::create_dir_all(&directory)?;
    }
    let mut copies = Vec::with_capacity(icons.len());
    for icon in icons {
        let destination = directory.join(icon.file_name());
        std::fs::write(&destination, std::fs::read(&icon.path)?)?;
        copies.push(destination);
    }
    let module = out_dir.join("icons.rs");
    std::fs::write(&module, module_source(icons))?;
    Ok((module, copies))
}

/// The generated `icons.rs` (plain items, no inner attributes: it is
/// `include!`d).
pub fn module_source(icons: &[Icon]) -> String {
    let mut out = String::from(
        "// Generated by zant-build from assets/icons/*.png. Do not edit.\n\
         //\n\
         // `assets/icons/<name>.png` is `icon_<name>` (`-` → `_`); include this\n\
         // file where the bytes are needed:\n\
         //\n\
         //     mod icons {\n\
         //         include!(concat!(env!(\"OUT_DIR\"), \"/icons.rs\"));\n\
         //     }\n\n",
    );
    for icon in icons {
        out.push_str(&format!(
            "#[allow(dead_code)]\npub const {}: &'static [u8] = include_bytes!(\"_icons/{}\");\n",
            icon.name,
            escape(&icon.file_name())
        ));
    }
    out.push_str(
        "\n/// Every icon by name: `(\"tray-dark\", icon_tray_dark)`.\n\
         #[allow(dead_code)]\n\
         pub const ICONS: &[(&'static str, &'static [u8])] = &[\n",
    );
    for icon in icons {
        out.push_str(&format!(
            "    (\"{}\", {}),\n",
            escape(&icon.stem),
            icon.name
        ));
    }
    out.push_str("];\n");
    out
}

/// Escapes a file name / stem for a Rust string literal.
fn escape(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    for character in value.chars() {
        match character {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            other => out.push(other),
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    // Zig `addAppIcons`: every PNG in `assets/icons` is `icon_<stem>` with
    // `-` replaced by `_`.

    #[test]
    fn every_png_is_an_icon_with_dashes_replaced() {
        let root = crate::tests::fixture_root();
        let icons = enumerate(&root).expect("icons");
        let names: Vec<&str> = icons.iter().map(|icon| icon.name.as_str()).collect();
        assert_eq!(
            names,
            [
                "icon_app_macos",
                "icon_app_windows",
                "icon_statusbar",
                "icon_tray_dark",
                "icon_tray_light",
            ]
        );
        assert_eq!(icons[3].stem, "tray-dark");
        assert_eq!(icons[3].file_name(), "tray-dark.png");
        assert!(!icons.iter().any(|icon| icon.name.contains('-')));
    }

    #[test]
    fn a_project_without_icons_has_none() {
        let directory = crate::tests::temp_dir("icons-none");
        assert_eq!(enumerate(&directory).expect("enumerate"), Vec::new());
    }

    #[test]
    fn the_generated_module_declares_include_bytes_constants() {
        let icons = [
            Icon {
                name: "icon_tray_dark".to_owned(),
                stem: "tray-dark".to_owned(),
                path: PathBuf::new(),
            },
            Icon {
                name: "icon_app_windows".to_owned(),
                stem: "app-windows".to_owned(),
                path: PathBuf::new(),
            },
        ];
        let source = module_source(&icons);
        assert!(source.contains(
            "#[allow(dead_code)]\npub const icon_tray_dark: &'static [u8] = \
             include_bytes!(\"_icons/tray-dark.png\");"
        ));
        assert!(source.contains("pub const ICONS: &[(&'static str, &'static [u8])] = &["));
        assert!(source.contains("    (\"tray-dark\", icon_tray_dark),"));
        assert!(source.contains("    (\"app-windows\", icon_app_windows),"));
        // no inner attributes: the file is intended for `include!`
        assert!(!source.contains("#!["));
    }
}
