use super::*;

#[test]
fn unused_child_props_are_not_stored() {
    for parameter in ["", "props: Props", "{ label }: Props"] {
        for state in ["", "const [count, setCount] = useState<u32>(0);"] {
            let source = generated(&format!(
                r#"
import {{ useState, Text }} from "zant";
import type {{ u32 }} from "zant";
interface Props {{ label: string; }}
function Child({parameter}) {{
  {state}
  return <Text>Child</Text>;
}}
export default function App() {{ return <Text>App</Text>; }}
"#
            ))
            .source;
            assert!(
                !struct_fields(&source, "Child").contains(&"props: ChildProps_,".to_owned()),
                "{source}"
            );
            assert!(
                source.contains("pub fn build(_props: ChildProps_"),
                "{source}"
            );
            assert!(!source.contains("props: Default::default()"), "{source}");
            assert!(!source.contains("instance.props ="), "{source}");
        }
    }
}

#[test]
fn child_props_read_only_in_handlers_are_kept() {
    for parameter in ["props: Props", "{ label }: Props"] {
        let label = if parameter.starts_with("props:") {
            "props.label"
        } else {
            "label"
        };
        let source = generated(&format!(
            r#"
import {{ Button, Text }} from "zant";
interface Props {{ label: string; }}
function Child({parameter}) {{
  return <Button onClick={{() => console.log({label})}}>Child</Button>;
}}
function Empty() {{ return <Text>Empty</Text>; }}
export default function App() {{ return <Text>App</Text>; }}
"#
        ))
        .source;
        assert!(
            struct_fields(&source, "Child").contains(&"props: ChildProps_,".to_owned()),
            "{source}"
        );
        assert!(
            source.contains("pub fn build(props: ChildProps_"),
            "{source}"
        );
        assert!(source.contains("self.props"), "{source}");
        assert!(
            !struct_fields(&source, "Empty").contains(&"props: EmptyProps_,".to_owned()),
            "{source}"
        );
        assert!(
            source.contains("pub fn build(_props: EmptyProps_"),
            "{source}"
        );
    }
}

/// The fields of the generated root struct, in order.
/// The fields of `pub struct Name`, without the `_render_<state>` copies of
/// the state (React's per-render state, checked on their own).
pub(super) fn struct_fields(source: &str, name: &str) -> Vec<String> {
    let start = source
        .find(&format!("pub struct {name} {{\n"))
        .unwrap_or_else(|| panic!("struct {name} in\n{source}"));
    let rest = &source[start..];
    let end = rest.find("\n}\n").expect("struct end");
    rest[..end]
        .lines()
        .skip(1)
        .map(|line| line.trim().to_owned())
        .filter(|line| !line.is_empty() && !line.starts_with("_render_"))
        .collect()
}

/// The body of `impl Default for Name`, one field per line.
pub(super) fn default_fields(source: &str, name: &str) -> Vec<String> {
    let start = source
        .find(&format!("impl Default for {name} {{\n"))
        .unwrap_or_else(|| panic!("impl Default for {name} in\n{source}"));
    let rest = &source[start..];
    let end = rest.find("\n    }\n}\n").expect("default end");
    rest[..end]
        .lines()
        .filter_map(|line| {
            let line = line.trim();
            if line.contains(": ")
                && !line.starts_with("Self")
                && !line.starts_with("fn ")
                && !line.starts_with("_render_")
            {
                Some(line.trim_end_matches(',').to_owned())
            } else {
                None
            }
        })
        .collect()
}

// ── the counter golden ────────────────────────────────────────────────

pub(super) const COUNTER: &str = r#"
import { useState, View, Text, Button, Input } from "zant";
import type { u32 } from "zant";

export default function Counter() {
  const [count, setCount] = useState<u32>(0);
  const [name, setName] = useState("Zant");
  const [notify, setNotify] = useState(false);
  return (
    <View padding={24}>
      <Input key="name" value={name} onChange={setName} />
      <Button key="reset" text="Reset" disabled={count === 0} onClick={() => setCount(0)} />
      <Text key="note">Notifications are on</Text>
    </View>
  );
}
"#;

#[test]
fn counter_lowers_to_the_reviewed_component_shape() {
    let file = generated(COUNTER);
    let source = &file.source;
    assert!(
        source.starts_with("// @generated by zant-tsx from src/App.tsx — do not edit."),
        "{source}"
    );
    assert!(source.contains("#![allow(clippy::redundant_clone)]"));
    assert!(source.contains("#![allow(clippy::too_many_arguments)]"));
    assert!(source.contains("use zant::tsx;"));
    assert!(source.contains("use zant::ui;"));

    assert!(!source.contains("#[derive(Default)]\npub struct Counter"));
    // §6.1: plain fields, `impl Default` from the useState initial values.
    assert_eq!(
        vec!["count: u32,", "name: zant::Str,", "notify: bool,"],
        struct_fields(source, "Counter"),
        "{source}"
    );
    assert_eq!(
        vec![
            "count: 0u32".to_owned(),
            "name: zant::Str::from(\"Zant\")".to_owned(),
            "notify: false".to_owned(),
        ],
        default_fields(source, "Counter"),
        "{source}"
    );

    // `impl ui::App for Counter` holds `render`; the handlers are inherent.
    assert!(
        source.contains("impl ui::App for Counter {\n    fn render(&mut self) -> ui::Node {"),
        "{source}"
    );

    // §5: `onChange={setName}` becomes a setter adapter method, and
    // `onClick={() => setCount(0)}` a numbered private handler.
    assert!(
        source.contains("fn _set_name(&mut self, value: &str) {"),
        "{source}"
    );
    assert!(source.contains("fn _on_click"), "{source}");
    assert!(
        source.contains("self.count = 0u32;"),
        "the reset handler body is generated\n{source}"
    );
    // the whole module was validated with `syn` inside `generate`.
    assert!(syn::parse_file(source).is_ok());
}

