const LOCAL_DESTRUCTURE_RENAME: &str = r#"
import { View, Text, Button, useState, useTheme } from "zant";
interface Item { title: string; id: number; }
function makeItem(): Item { return { title: "Hello", id: 7 }; }
function localLabel(item: Item): string {
  const { title: label, id } = item;
  return `${id}: ${label} ${item.title}`;
}
function useTitle() {
  const [title, setTitle] = useState("Hook");
  return { title, rename: () => setTitle("Renamed") };
}
export default function App() {
  const [text, setText] = useState("");
  const item: Item = makeItem();
  const { title: label, id } = item;
  const inlineItem: { title: string } = { title: "Inline" };
  const { title: inlineLabel } = inlineItem;
  const { title: again } = makeItem();
  let { title: mutable }: Item = item;
  mutable = "Changed";
  const theme = useTheme();
  const { colorText: ink } = theme;
  const { title: hookTitle, rename: renameHook } = useTitle();
  function rename() {
    const { title: next } = makeItem();
    setText(next);
  }
  return <View><Text color={ink}>{label} {inlineLabel} {id} {again} {mutable} {text} {localLabel(item)}</Text>
    <Button onClick={rename}>Rename</Button>
    <Button onClick={renameHook}>{hookTitle}</Button></View>;
}
"#;

/// A child's effect cleanup also runs after the child unmounted (React):
/// the cleanup field is a `tsx::Cleanup` (dropping it queues the cleanup)
/// and the cleanup action falls back to a default instance.
const EFFECT_CLEANUP_UNMOUNT: &str = r#"
import { useState, useEffect, View, Text, Button } from "zant";
function Ticker() {
  const [ticks, setTicks] = useState(0);
  useEffect(() => {
    const id = setInterval(() => setTicks((n) => n + 1), 1000);
    return () => clearInterval(id);
  }, []);
  return <Text>{ticks}</Text>;
}
export default function App() {
  const [shown, setShown] = useState(true);
  return <View>{shown && <Ticker />}<Button onClick={() => setShown(!shown)}>toggle</Button></View>;
}
"#;

#[test]
fn an_effect_cleanup_runs_after_its_component_unmounts() {
    let generated = compile("effect_cleanup_unmount", EFFECT_CLEANUP_UNMOUNT);
    contains(&generated, ": tsx::Cleanup,");
    contains(&generated, ".set(ui::Action::new(");
    contains(&generated, "let mut _unmounted = Ticker::default();");
}

const MODULES: &[(&str, &str)] = &[
    ("effect_cleanup_unmount", EFFECT_CLEANUP_UNMOUNT),
    (
        "callback_defaults",
        include_str!("../testdata/tsx/callback_defaults.tsx"),
    ),
    ("local_destructure_rename", LOCAL_DESTRUCTURE_RENAME),
    ("child_callbacks", CHILD_CALLBACKS),
    ("props_object_callbacks", PROPS_OBJECT_CALLBACKS),
    ("optional_node", OPTIONAL_NODE),
    ("rich_text_tail", RICH_TEXT_TAIL),
    ("list_in_child", LIST_IN_CHILD),
    ("optional_children", OPTIONAL_CHILDREN),
];

fn imported_callback_defaults() -> zant_tsx::compile::GeneratedProject {
    use zant_tsx::compile::{SourceFile, compile_project};
    compile_project(&[
        SourceFile::tsx("callbacks.tsx", "export function save(): void {} export const toggle = (checked: boolean) => {}; export function pair(id: number, text: string): void {}"),
        SourceFile::tsx("imported_defaults.tsx", r#"
import { save, toggle, pair } from "./callbacks";
import { Button, Checkbox, View } from "zant";
function Child({ onClose = save, onToggle = toggle, onPair = pair }: {
    onClose?: () => void; onToggle?: (checked: boolean) => void; onPair?: (id: number, text: string) => void;
}) {
    return <View><Button onClick={onClose}>Close</Button>
      <Checkbox checked={false} onChange={onToggle} />
      <Button onClick={() => { onClose(); onPair(1, "x"); }}>Pair</Button></View>;
}
export default function App() { return <Child />; }
"#),
    ]).expect("imported callback defaults compile")
}

