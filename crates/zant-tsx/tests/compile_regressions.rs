//! Regression tests for four `zant-tsx` code generation bugs:
//!
//! 1. a child component's callback prop runs synchronously inside the handler
//!    (it used to be queued through `ui::effect`, which `ui::begin_frame`
//!    clears before the effects run, so the callback never ran);
//! 2. an `Option<Node>` prop accepts a bare element (`footer={<Row>…</Row>}`);
//! 3. rich text keeps a literal text child after an expression child
//!    (`…<Link>link</Link>{cond}.` lost the `.`);
//! 4. a `<List>` inside a non-root component can clone its state slot instead
//!    of borrowing `self` while the row closures use it.
//!
//! Every module is generated by the real compiler and then compiled against
//! `crates/zant` in one temporary crate (the pattern of `tests/golden.rs`), so
//! the assertions cover generated code that really builds.

use std::path::{Path, PathBuf};
use std::process::Command;

fn compile(name: &str, source: &str) -> String {
    zant_tsx::compile::compile(source, &format!("{name}.tsx")).unwrap_or_else(|diag| {
        panic!(
            "{name}.tsx does not compile: {} ({})",
            diag.msg,
            zant_tsx::error::render_diag(&format!("{name}.tsx"), source, &diag)
        )
    })
}

/// Whitespace-insensitive containment: `prettyplease` reformats the generated
/// module and keeps macro tokens (`nodes![…]`) as written.
fn squeeze(text: &str) -> String {
    text.chars().filter(|ch| !ch.is_whitespace()).collect()
}

#[track_caller]
fn contains(source: &str, expected: &str) {
    let squeezed = squeeze(source);
    assert!(
        squeezed.contains(&squeeze(expected)),
        "missing `{expected}` in:\n{source}"
    );
}

/// 1. Child callbacks: a child handler calls the parent's callback prop with
///    the runtime context, synchronously, including through a helper function.
const CHILD_CALLBACKS: &str = r#"
import { useState, View, Row, Text, Button, Checkbox } from "zant";
import type { u32 } from "zant";

interface StepProps {
  label: string;
  onStep: () => void;
  onPick: (id: u32) => void;
  onRename: (value: string) => void;
  onToggle: (checked: boolean) => void;
}

function Stepper({ label, onStep, onPick, onRename, onToggle }: StepProps) {
  const [n, setN] = useState<u32>(0);
  function add(delta: u32) {
    setN(n + delta);
    onStep();
  }
  return (
    <Row gap={8}>
      <Text key="label">{label}</Text>
      <Button key="plus" onClick={() => add(1)}>+</Button>
      <Button key="pick" onClick={() => onPick(7)}>Pick</Button>
      <Button key="rename" onClick={() => onRename("x")}>Rename</Button>
      <Checkbox key="toggle" checked={false} onChange={(checked) => onToggle(checked)}>T</Checkbox>
    </Row>
  );
}

export default function App() {
  const [count, setCount] = useState<u32>(0);
  const [picked, setPicked] = useState<u32>(0);
  const [name, setName] = useState("");
  return (
    <View>
      <Stepper label="Steps" onStep={() => setCount(count + 1)} onPick={(id) => setPicked(id)}
        onRename={(value) => setName(value)} onToggle={(checked) => setPicked(checked ? 1 : 0)} />
      <Text>{count} {picked} {name}</Text>
    </View>
  );
}
"#;

