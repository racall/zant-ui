//! Regression tests for four `zant-tsx` code generation bugs:
//!
//! 1. a child component's callback prop runs synchronously inside the handler
//!    (it used to be queued through `ui::effect`, which `ui::begin_frame`
//!    clears before the effects run, so the callback never ran);
//! 2. an `Option<Node>` prop accepts a bare element (`footer={<Row>…</Row>}`);
//! 3. rich text keeps a literal text child after an expression child
//!    (`…<Link>link</Link>{cond}.` lost the `.`);
//! 4. a `<List>` inside a non-root component can clone its state slot instead
//!    of borrowing `self` while the row closures use it.
//!
//! Every module is generated by the real compiler and then compiled against
//! `crates/zant` in one temporary crate (the pattern of `tests/golden.rs`), so
//! the assertions cover generated code that really builds.

use std::path::{Path, PathBuf};
use std::process::Command;

fn compile(name: &str, source: &str) -> String {
    zant_tsx::compile::compile(source, &format!("{name}.tsx")).unwrap_or_else(|diag| {
        panic!(
            "{name}.tsx does not compile: {} ({})",
            diag.msg,
            zant_tsx::error::render_diag(&format!("{name}.tsx"), source, &diag)
        )
    })
}

/// Whitespace-insensitive containment: `prettyplease` reformats the generated
/// module and keeps macro tokens (`nodes![…]`) as written.
fn squeeze(text: &str) -> String {
    text.chars().filter(|ch| !ch.is_whitespace()).collect()
}

#[track_caller]
fn contains(source: &str, expected: &str) {
    let squeezed = squeeze(source);
    assert!(
        squeezed.contains(&squeeze(expected)),
        "missing `{expected}` in:\n{source}"
    );
}

/// 1. Child callbacks: a child handler calls the parent's callback prop with
///    the runtime context, synchronously, including through a helper function.
const CHILD_CALLBACKS: &str = r#"
import { useState, View, Row, Text, Button, Checkbox } from "zant";
import type { u32 } from "zant";

interface StepProps {
  label: string;
  onStep: () => void;
  onPick: (id: u32) => void;
  onRename: (value: string) => void;
  onToggle: (checked: boolean) => void;
}

function Stepper({ label, onStep, onPick, onRename, onToggle }: StepProps) {
  const [n, setN] = useState<u32>(0);
  function add(delta: u32) {
    setN(n + delta);
    onStep();
  }
  return (
    <Row gap={8}>
      <Text key="label">{label}</Text>
      <Button key="plus" onClick={() => add(1)}>+</Button>
      <Button key="pick" onClick={() => onPick(7)}>Pick</Button>
      <Button key="rename" onClick={() => onRename("x")}>Rename</Button>
      <Checkbox key="toggle" checked={false} onChange={(checked) => onToggle(checked)}>T</Checkbox>
    </Row>
  );
}

export default function App() {
  const [count, setCount] = useState<u32>(0);
  const [picked, setPicked] = useState<u32>(0);
  const [name, setName] = useState("");
  return (
    <View>
      <Stepper label="Steps" onStep={() => setCount(count + 1)} onPick={(id) => setPicked(id)}
        onRename={(value) => setName(value)} onToggle={(checked) => setPicked(checked ? 1 : 0)} />
      <Text>{count} {picked} {name}</Text>
    </View>
  );
}
"#;

/// 1b. The same through a non-destructured `props` parameter (`props.onSave(..)`).
const PROPS_OBJECT_CALLBACKS: &str = r#"
import { useState, View, Row, Text, Button } from "zant";
import type { u32 } from "zant";

interface ChildProps {
  title: string;
  onSave: () => void;
  onPick: (id: u32) => void;
}

function Child(props: ChildProps) {
  return (
    <Row>
      <Text>{props.title}</Text>
      <Button key="save" onClick={() => props.onSave()}>Save</Button>
      <Button key="pick" onClick={() => props.onPick(3)}>Pick</Button>
    </Row>
  );
}

export default function App() {
  const [n, setN] = useState<u32>(0);
  return (
    <View>
      <Child title="x" onSave={() => setN(n + 1)} onPick={(id) => setN(id)} />
      <Text>{n}</Text>
    </View>
  );
}
"#;

/// 2. `Option<Node>` prop with a bare element.
const OPTIONAL_NODE: &str = r#"
import { useState, Modal, Row, Button, View, Paragraph } from "zant";

export default function App() {
  const [open, setOpen] = useState(false);
  return (
    <View>
      {open && (
        <Modal key="dialog" title="Save changes" onClose={() => setOpen(false)}
          footer={<Row gap={8} justifyContent="flex-end"><Button key="cancel" onClick={() => setOpen(false)}>Cancel</Button></Row>}>
          <Paragraph>hi</Paragraph>
        </Modal>
      )}
    </View>
  );
}
"#;

/// 3. Rich text with a literal after an expression child.
const RICH_TEXT_TAIL: &str = r#"
import { useState, Text, Link } from "zant";
import type { u32 } from "zant";

export default function App() {
  const [docs, setDocs] = useState<u32>(0);
  return (
    <Text key="rich">
      inline <Link onClick={() => setDocs(docs + 1)}>link</Link>
      {docs > 0 && ` (opened ${docs}×)`}.
    </Text>
  );
}
"#;

/// 4. `<List>` inside a component with props and local state, whose row
///    handler updates that state and calls a callback prop.
const LIST_IN_CHILD: &str = r#"
import { useState, List, View, Row, Text, Button } from "zant";
import type { u32 } from "zant";

interface RowData { id: u32; title: string; }

export function ListView({ rows, onPick }: { rows: RowData[]; onPick: (id: u32) => void }) {
  const [picked, setPicked] = useState<u32>(0);
  return (
    <View>
      <Text>Picked {picked}</Text>
      <List data={rows} itemHeight={40} keyExtractor={(row) => row.id}
        renderItem={(row) => (
          <Row>
            <Text>{row.title}</Text>
            <Button onClick={() => { setPicked(row.id); onPick(row.id); }}>Pick</Button>
          </Row>
        )} />
    </View>
  );
}

export default function App() {
  const [picked, setPicked] = useState<u32>(0);
  return (
    <View>
      <ListView rows={[{ id: 1, title: "a" }]} onPick={(id) => setPicked(id)} />
      <Text>{picked}</Text>
    </View>
  );
}
"#;

const MODULES: &[(&str, &str)] = &[
    ("child_callbacks", CHILD_CALLBACKS),
    ("props_object_callbacks", PROPS_OBJECT_CALLBACKS),
    ("optional_node", OPTIONAL_NODE),
    ("rich_text_tail", RICH_TEXT_TAIL),
    ("list_in_child", LIST_IN_CHILD),
];

#[test]
fn child_callback_props_run_synchronously() {
    let generated = compile("child_callbacks", CHILD_CALLBACKS);
    // no deferred queue: `ui::begin_frame` clears effects before they run
    assert!(
        !generated.contains("ui::effect("),
        "a callback prop must not be deferred through ui::effect:\n{generated}"
    );
    // the parent callback classes: `() => void` is an Action, a typed
    // parameter is an `Rc<dyn Fn(&mut ActionCx, …)>`, `string` is a TextAction
    contains(
        &generated,
        "fn _on_click1(&mut self, _cx: &mut ui::ActionCx<'_>)",
    );
    contains(&generated, "(self.props.onPick.clone())(_cx, 7u32)");
    contains(&generated, "(self.props.onRename.clone()).call(_cx,");
    contains(
        &generated,
        "(self.props.onToggle.clone()).call(_cx, checked)",
    );
    // the handler that calls a callback through a helper passes the context on
    contains(
        &generated,
        "fn add(&mut self, _cx: &mut ui::ActionCx<'_>, delta: u32)",
    );
    contains(&generated, "self.add(_cx, 1u32)");
    // the `boolean` callback prop keeps its BoolAction shape
    contains(
        &generated,
        "fn _on_change4(&mut self, _cx: &mut ui::ActionCx<'_>, checked: bool)",
    );
}

#[test]
fn a_props_object_callback_prop_also_runs_synchronously() {
    let generated = compile("props_object_callbacks", PROPS_OBJECT_CALLBACKS);
    contains(
        &generated,
        "fn _on_click1(&mut self, _cx: &mut ui::ActionCx<'_>)",
    );
    contains(&generated, "(self.props.clone().onSave.clone()).call(_cx)");
    contains(&generated, "(self.props.clone().onPick.clone())(_cx, 3u32)");
}

#[test]
fn optional_node_prop_accepts_a_bare_element() {
    let generated = compile("optional_node", OPTIONAL_NODE);
    contains(&generated, "footer: Some(ui::row(ui::BoxOptions {");
    assert!(
        !squeeze(&generated).contains("footer:ui::row("),
        "an Option<Node> prop must wrap the element in Some(..):\n{generated}"
    );
}

#[test]
fn rich_text_keeps_a_literal_after_an_expression() {
    let generated = compile("rich_text_tail", RICH_TEXT_TAIL);
    // the final `.` after `{…}` becomes part of the same span's format pattern
    contains(&generated, "format!(\"{}.\", if");
}

#[test]
fn list_in_a_child_component_clones_its_state_slot() {
    let generated = compile("list_in_child", LIST_IN_CHILD);
    // the row closures outlive the `&mut self` build: the list and the
    // component's local state slot are cloned into locals first (E0505)
    contains(&generated, "let _list = self._list1.clone();");
    contains(&generated, "let _state = self._state.clone();");
    contains(&generated, "ui::list(&_list, ui::ListOptions {");
    assert!(
        !squeeze(&generated).contains("ui::list(&self._list"),
        "the list state must not be borrowed from self:\n{generated}"
    );
    // the row handler upgrades the hoisted slot and calls the callback prop
    contains(&generated, "let _state = _state.clone();");
    contains(&generated, "(cap.onPick.clone())(_cx,");
}

#[test]
fn the_regression_modules_compile_against_the_runtime() {
    let crate_dir = temporary_crate_dir();
    let src_dir = crate_dir.join("src");
    let _ = std::fs::remove_dir_all(&src_dir);
    std::fs::create_dir_all(&src_dir).expect("create temp crate src");
    let zant_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../zant");
    let cargo_toml = format!(
        "[package]\nname = \"zant-tsx-regressions\"\nversion = \"0.0.0\"\nedition = \"2024\"\n\n\
         [dependencies]\nzant = {{ path = {:?} }}\n\n[workspace]\n",
        zant_dir.to_string_lossy()
    );
    std::fs::write(crate_dir.join("Cargo.toml"), cargo_toml).expect("write Cargo.toml");
    let mut modules = String::from("#![allow(dead_code)]\n");
    for (name, source) in MODULES {
        let generated = compile(name, source);
        std::fs::write(src_dir.join(format!("{name}.rs")), generated).expect("write module");
        modules.push_str(&format!("#[path = \"{name}.rs\"]\nmod {name};\n"));
    }
    modules.push_str("fn main() {}\n");
    std::fs::write(src_dir.join("main.rs"), modules).expect("write main.rs");
    let (success, text) = run_cargo_check(&crate_dir);
    assert!(
        success,
        "the regression modules do not compile against zant:\n{text}"
    );
}

fn temporary_crate_dir() -> PathBuf {
    let target = std::env::var_os("CARGO_TARGET_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../target"));
    let dir = target.join("zant-tsx-regressions");
    std::fs::create_dir_all(&dir).expect("create temp crate directory");
    dir
}

fn run_cargo_check(crate_dir: &Path) -> (bool, String) {
    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".to_owned());
    let run = |offline: bool| {
        let mut command = Command::new(&cargo);
        command
            .current_dir(crate_dir)
            .env("CARGO_TARGET_DIR", crate_dir.join("target"))
            .arg("check")
            .arg("--quiet")
            .arg("--message-format=short");
        if offline {
            command.arg("--offline");
        }
        command.output()
    };
    let output = run(true).expect("run cargo check");
    if output.status.success() {
        return (true, String::from_utf8_lossy(&output.stderr).into_owned());
    }
    match run(false) {
        Ok(retry) if retry.status.success() => {
            (true, String::from_utf8_lossy(&retry.stderr).into_owned())
        }
        Ok(retry) => (false, String::from_utf8_lossy(&retry.stderr).into_owned()),
        Err(error) => (
            false,
            format!(
                "{}\n(and the retry without --offline failed: {error})",
                String::from_utf8_lossy(&output.stderr)
            ),
        ),
    }
}
