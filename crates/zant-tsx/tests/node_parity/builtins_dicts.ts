// Dictionary key equality and iteration order, including delete/re-add.
export function run(): void {
  const map = new Map<string, number>([["b", 2], ["a", 1], ["b", 3]]);
  map.set("c", 4);
  map.set("a", 5);
  const deleted = map.delete("b");
  const missing = map.delete("missing");
  map.set("b", 6);
  console.log("map", deleted, missing, map.size, map.get("a") ?? -1, map.get("missing") ?? -1, map.has("b"));
  console.log("map-order", [...map.keys()].join(","), JSON.stringify([...map.values()]), JSON.stringify([...map.entries()]));
  let pairs = "";
  for (const [k, v] of map) pairs += k + ":" + String(v) + ";";
  console.log("map-for", pairs);
  const numeric = new Map<number, string>([[NaN, "first"], [-0, "zero"], [NaN, "last"]]);
  numeric.set(0, "updated");
  numeric.delete(NaN);
  numeric.set(NaN, "again");
  console.log("map-numbers", numeric.size, numeric.get(NaN) ?? "missing", numeric.get(-0) ?? "missing", numeric.has(NaN));
  console.log("map-number-order", JSON.stringify([...numeric.keys()].map(x => String(x))), JSON.stringify([...numeric.values()]));
  for (const key of numeric.keys()) console.log("map-zero-sign", String(key), String(1 / key));
  const clearMap = new Map<boolean, number>([[true, 1], [false, 2]]);
  clearMap.clear();
  clearMap.set(false, 3);
  console.log("map-clear", clearMap.size, clearMap.has(true), JSON.stringify([...clearMap.entries()]));
  const set = new Set<string>(["b", "a", "b"]);
  set.add("c");
  const setDeleted = set.delete("a");
  set.add("a");
  set.add("b");
  console.log("set", setDeleted, set.size, set.has("missing"), [...set.values()].join(","), [...set.keys()].join(","));
  let setOrder = "";
  for (const x of set) setOrder += x + ";";
  console.log("set-for", setOrder);
  const numbers = new Set<number>([NaN, NaN, -0, 0, 2]);
  numbers.delete(0);
  numbers.add(-0);
  console.log("set-numbers", numbers.size, numbers.has(NaN), numbers.has(0), JSON.stringify([...numbers.values()].map(x => String(x))));
  for (const x of numbers) console.log("set-zero-sign", String(x), String(1 / x));
  const cleared = new Set<number>([1, 2]);
  cleared.clear();
  cleared.add(3);
  console.log("set-clear", cleared.size, cleared.has(1), JSON.stringify([...cleared.values()]));
  // Integer-like keys are left out: Zant keeps insertion order (documented).
  const record: Record<string, number> = { z: 1, "k10": 10, "k2": 2, "k01": 1, a: 3, "k0": 0, "k4294967295": 5, "k4294967294": 4 };
  record["k3"] = 30;
  record.z = 9;
  delete record["a"];
  record["a"] = 7;
  console.log("record-read", record.z ?? -1, record["missing"] ?? -1, "k2" in record, "missing" in record);
  console.log("record-keys", Object.keys(record).join(","));
  console.log("record-values", JSON.stringify(Object.values(record)));
  console.log("record-entries", JSON.stringify(Object.entries(record)));
  let recordOrder = "";
  for (const key in record) recordOrder += key + ";";
  console.log("record-for", recordOrder);
  const entries: [string, number][] = [["b", 1], ["k2", 2], ["a", 3], ["k1", 4], ["b", 5]];
  const from: Record<string, number> = Object.fromEntries(entries);
  console.log("fromEntries", Object.keys(from).join(","), JSON.stringify(Object.values(from)));
  const empty: Record<string, number> = {};
  console.log("record-empty", Object.keys(empty).length, Object.values(empty).length, Object.entries(empty).length);
}
