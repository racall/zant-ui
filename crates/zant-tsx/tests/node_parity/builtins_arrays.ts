// All mutations target fresh locals, before exposing the whole value.
export function run(): void {
  const empty: number[] = [];
  console.log("empty", empty.length, JSON.stringify(empty.map(x => x + 1)), empty.some(x => x > 0), empty.every(x => x > 0));
  console.log("empty-find", empty.find(x => x > 0) ?? -1, empty.findIndex(x => x > 0), empty.indexOf(0), empty.includes(0));
  console.log("empty-reduce", empty.reduce((a, b) => a + b, 17));
  const one: number[] = [7];
  console.log("one-reduce", one.reduce((a, b) => a - b, 20));
  const values: number[] = [4, 0, -2, 4, NaN];
  console.log("functional", JSON.stringify(values.map((x, i) => x + i)), JSON.stringify(values.filter(x => x >= 0)));
  console.log("find", values.find(x => x === 0) ?? 99, values.findIndex(x => x === 4), values.some(x => x < 0), values.every(x => x >= 0));
  console.log("nan-search", values.indexOf(NaN), values.includes(NaN), values.indexOf(-0), values.includes(-0));
  console.log("reduce-index", one.reduce((a, x, i) => a + x + i, 10), [2, 3, 4].reduce((a, x, i) => a + x * i, 0));
  console.log("slice", JSON.stringify(values.slice(-4, -1)), JSON.stringify(values.slice(-99, 99)), JSON.stringify(values.slice(4, 1)));
  console.log("slice-special", JSON.stringify(values.slice(NaN, 2.9)), JSON.stringify(values.slice(-Infinity, Infinity)));
  console.log("spread-concat", JSON.stringify([...one, 8, ...empty]), JSON.stringify(one.concat([8, 9], empty)));
  const strings: string[] = ["", "a", "中", ""];
  console.log("join", strings.join(","), strings.join("|"), strings.join(""));
  const a: number[] = [1, 2, 3, 4];
  const removed = a.splice(-2, 999, 8, 9, 10);
  console.log("splice-negative", JSON.stringify(removed), JSON.stringify(a));
  const b: number[] = [1, 2, 3];
  const inserted = b.splice(-99, 0, 7, 8);
  const tail = b.splice(99, 999, 9);
  console.log("splice-insert", JSON.stringify(inserted), JSON.stringify(tail), JSON.stringify(b));
  const c: number[] = [1, 2, 3, 4];
  const rest = c.splice(-2);
  console.log("splice-omitted", JSON.stringify(rest), JSON.stringify(c));
  const d: number[] = [1, 2, 3];
  const nanRemoved = d.splice(NaN, NaN, 9);
  const infRemoved = d.splice(1.9, Infinity, 8);
  console.log("splice-special", JSON.stringify(nanRemoved), JSON.stringify(infRemoved), JSON.stringify(d));
  const stack: number[] = [];
  const p0 = stack.pop();
  const s0 = stack.shift();
  const p1 = stack.push(3, 4);
  const u1 = stack.unshift(1, 2);
  const p2 = stack.pop();
  const s2 = stack.shift();
  stack[stack.length] = 5;
  stack[0] = 9;
  stack.reverse();
  console.log("mutations", p0 ?? -1, s0 ?? -1, p1, u1, p2 ?? -1, s2 ?? -1, JSON.stringify(stack));
  const fill: number[] = [1, 2, 3, 4, 5];
  fill.fill(0, -4, -1);
  fill.fill(9, 4, 1);
  console.log("fill-negative", JSON.stringify(fill));
  const fillSpecial: number[] = [1, 2, 3, 4];
  fillSpecial.fill(8, NaN, 2.9);
  fillSpecial.fill(7, -Infinity, -3);
  console.log("fill-special", JSON.stringify(fillSpecial));
  const fillEmpty: number[] = [];
  fillEmpty.fill(2);
  console.log("fill-empty", JSON.stringify(fillEmpty));
  const numeric: number[] = [10, 2, 1, 20, -1, -10, 0, -0, NaN, Infinity, -Infinity];
  numeric.sort();
  console.log("sort-default", JSON.stringify(numeric.map(x => String(x))));
  const words: string[] = ["z", "😀", "\uff61", "a", "10", "2", ""];
  words.sort();
  console.log("sort-utf16", JSON.stringify(words));
  const stable = [{ rank: 2, id: "a" }, { rank: 1, id: "b" }, { rank: 2, id: "c" }, { rank: 1, id: "d" }];
  stable.sort((a, b) => a.rank - b.rank);
  console.log("sort-stable", stable.map(x => x.id).join(""));
  const equal: number[] = [3, 1, 2];
  equal.sort((a, b) => NaN);
  console.log("sort-nan", JSON.stringify(equal));
  const ascending: number[] = [10, 2, 1, -1];
  ascending.sort((a, b) => a - b);
  console.log("sort-numeric", JSON.stringify(ascending));
  const sortEmpty: number[] = [];
  sortEmpty.sort();
  console.log("sort-empty", JSON.stringify(sortEmpty));
  const nested: number[][] = [[1, 2], [], [3]];
  console.log("nested", nested.length, nested[0][1], JSON.stringify(nested.map(xs => xs.length)), JSON.stringify(nested.slice(-2)));
  const source: number[] = [1, 2, 3];
  const copy = [...source];
  copy.push(4);
  const mapped = source.map(x => x * 2);
  mapped[0] = 99;
  const sliced = source.slice(1);
  sliced.reverse();
  console.log("fresh-copies", JSON.stringify(source), JSON.stringify(copy), JSON.stringify(mapped), JSON.stringify(sliced));
}
