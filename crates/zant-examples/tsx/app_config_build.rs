// Shared body of the TSX example apps' `build.rs` (`crates/zant-examples/tsx/`).
//
// Each app has the same four-line `build.rs`:
//
// ```ignore
// include!("../app_config_build.rs");
//
// fn main() {
//     build_app();
// }
// ```
//
// `build_app` is the template's `zant_build::tsx_app()` step plus the one
// thing a Cargo workspace member cannot do: the template runs `zant sync` once
// and commits `src/app_config.rs`, but an example inside the workspace has to
// build with plain `cargo build --workspace`. So the helper writes the same
// `src/app_config.rs` from the `app.config.json` that
// `zant_build::try_tsx_app()` already parsed and validated — the TSX sources
// and the config stay the single source of truth, and no generated file is
// committed (it is in each app's `.gitignore`).
//
// The write is content-compared: `cargo:rerun-if-changed` covers the whole
// `src/` directory, so rewriting an unchanged file would rerun the build
// script on every build.
//
// `zant_build::try_tsx_app` is `zant_build::tsx_app()` without the panic: it
// compiles `src/**/*.tsx` and `native/*.ts` into `$OUT_DIR`, copies imported
// assets, writes `native/spec.rs`, and applies the platform extras (icons,
// Windows manifest, pdfium.dll).

/// Runs the app's build: TSX → Rust in `$OUT_DIR` and `src/app_config.rs`.
pub fn build_app() {
    set_rustc_version();
    let report = match zant_build::try_tsx_app() {
        Ok(report) => report,
        Err(error) => panic!("zant-build: {error}"),
    };
    let Some(config) = report.config.as_ref() else {
        panic!("the example has no app.config.json");
    };
    let app_root = std::env::var_os("CARGO_MANIFEST_DIR")
        .expect("cargo sets CARGO_MANIFEST_DIR for build scripts");
    let path = std::path::Path::new(&app_root).join("src/app_config.rs");
    write_if_changed(&path, app_config_source(config).as_bytes());
}

/// `RUSTC_VERSION` is the Rust version the example native module reports; the
/// template's `build.rs` prints the same environment variable.
fn set_rustc_version() {
    let rustc = std::env::var("RUSTC").unwrap_or_else(|_| "rustc".to_string());
    if let Ok(output) = std::process::Command::new(rustc).arg("--version").output() {
        let line = String::from_utf8_lossy(&output.stdout);
        let version = line.trim();
        let version = version.strip_prefix("rustc ").unwrap_or(version);
        println!("cargo:rustc-env=RUSTC_VERSION={version}");
    }
}

/// Writes `data` only when it differs, so the `src/` directory watch does not
/// see a touched file and the build script does not rerun on every build
/// (`zant-build` does the same for `native/spec.rs`).
fn write_if_changed(path: &std::path::Path, data: &[u8]) {
    if std::fs::read(path).is_ok_and(|existing| existing == data) {
        return;
    }
    std::fs::write(path, data).expect("write src/app_config.rs");
}

/// `src/app_config.rs`: the `zant sync`-generated file of the template,
/// restricted to the fields a TSX entry reads (`zant::tsx::app::Config`); the
/// generated template file carries the same `#![allow(dead_code)]` because an
/// app may not read every field.
fn app_config_source(config: &zant_build::AppConfig) -> String {
    let window = &config.window;
    format!(
        "\
// Generated by `build.rs` from app.config.json. Do not edit by hand.
#![allow(dead_code)]

#[allow(non_upper_case_globals)]
pub const title: &str = \"{}\";
#[allow(non_upper_case_globals)]
pub const bundle_id: &str = \"{}\";
#[allow(non_upper_case_globals)]
pub const single_instance: bool = {};

#[allow(non_upper_case_globals)]
pub const window: zant::WindowOptions = zant::WindowOptions {{
    style: zant::WindowStyle::{},
    width: {},
    height: {},
    min_width: {},
    min_height: {},
    background: 0x{:08x},
    resizable: {},
    always_on_top: {},
    movable_by_background: {},
    center: {},
    titlebar_height: {},
    hidden: false,
    hidden_at_login: false,
}};
",
        escape_rust(&config.title),
        escape_rust(&config.bundle_id),
        config.single_instance,
        style_rust(&window.style),
        fmt_f32(window.width),
        fmt_f32(window.height),
        fmt_f32(window.min_width),
        fmt_f32(window.min_height),
        window.background,
        window.resizable,
        window.always_on_top,
        window.movable_by_background,
        window.center,
        fmt_f32(window.titlebar_height),
    )
}

/// The window style names of `app.config.json` (`zant-cli/src/app_config.rs`).
fn style_rust(style: &str) -> &'static str {
    if style == "hidden-titlebar" || style == "hidden_titlebar" {
        "HiddenTitlebar"
    } else if style == "borderless" {
        "Borderless"
    } else if style == "panel" {
        "Panel"
    } else {
        "Native"
    }
}

fn escape_rust(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for ch in text.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            other => out.push(other),
        }
    }
    out
}

/// Zig `{d}` prints `680` for an `f32`; Rust float literals need `680.0`.
fn fmt_f32(value: f32) -> String {
    if value.is_finite() && value.fract() == 0.0 {
        format!("{value:.1}")
    } else {
        format!("{value}")
    }
}
