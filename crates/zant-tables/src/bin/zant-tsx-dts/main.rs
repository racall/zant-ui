//! `zant-tsx-dts [--check] <path>...` generates the TSX editor declarations
//! (`zant.d.ts`) from the alias-merged tag table.
//!
//! ```text
//! cargo run -p zant-tables --bin zant-tsx-dts -- crates/zant-tsx/zant.d.ts
//! cargo run -p zant-tables --bin zant-tsx-dts -- --check crates/zant-tsx/zant.d.ts
//! ```

use std::process::ExitCode;

use zant_tsx::tags::{self, Content, Kind, Prop, Tag};

/// The handwritten runtime declarations, included inside `declare module "zant"`.
const DTS_API: &str = include_str!("dts_api.d.ts");

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let (check, paths) = match args.first().map(String::as_str) {
        Some("--check") => (true, &args[1..]),
        _ => (false, &args[..]),
    };
    if paths.is_empty() || paths[0].starts_with("--") {
        eprintln!("usage: zant-tsx-dts [--check] <path> ...");
        return ExitCode::from(2);
    }
    let output = generate();
    let mut code = ExitCode::SUCCESS;
    for path in paths {
        if check {
            match std::fs::read_to_string(path) {
                Ok(existing) if existing == output => {}
                Ok(_) => code = outdated(path),
                Err(error) => {
                    eprintln!("zant-tsx-dts: {path}: {error}");
                    code = ExitCode::from(1);
                }
            }
        } else if let Err(error) = std::fs::write(path, &output) {
            eprintln!("zant-tsx-dts: {path}: {error}");
            code = ExitCode::from(1);
        }
    }
    code
}

fn outdated(path: &str) -> ExitCode {
    eprintln!(
        "zant-tsx-dts: {path} is out of date; run \
         `cargo run -p zant-tables --bin zant-tsx-dts -- {path}`"
    );
    ExitCode::from(1)
}

fn generate() -> String {
    let mut out = String::with_capacity(256 * 1024);
    out.push_str(HEADER);
    for extension in [
        "png", "jpg", "jpeg", "gif", "webp", "ico", "svg", "txt", "bin",
    ] {
        out.push_str(&format!(
            "declare module \"*.{extension}\" {{ const bytes: Uint8Array; export default bytes; }}\n"
        ));
    }
    out.push_str("\ndeclare module \"zant\" {\n");
    out.push_str(DTS_API);
    out.push_str("\n  export interface Theme {\n");
    for prop in tags::theme_fields() {
        let ty = if prop.kind == Kind::Boolean {
            "boolean"
        } else {
            "number"
        };
        out.push_str(&format!("    {}: {ty};\n", prop.name));
    }
    out.push_str("  }\n\n");
    for tag in tags::all() {
        component(&mut out, tag);
    }
    out.push_str("}\n");
    out
}

/// The prologue of the generated file (the first line names this generator).
const HEADER: &str = "\
// Generated by `zant-tsx-dts` from the tag table and dts_api.d.ts. Do not edit.
// Editor types describe the TSX surface; zant-tsx validates the supported TS subset.
declare namespace JSX {
  interface Element { readonly __zantElement: unique symbol; }
  interface IntrinsicElements {}
  interface IntrinsicAttributes { key?: string | number; }
  interface ElementChildrenAttribute { children: {}; }
}

// Native Rust exports are checked by zant-tsx; the editor treats them as any.
declare module \"*.rs\";
// Assets (`import icon from \"./icon.png\"`): their bytes, embedded at compile time.
";

fn component(out: &mut String, tag: &Tag) {
    out.push_str(&format!(
        "  export interface {}Props {{\n    key?: string | number;\n",
        tag.name
    ));
    for prop in &tag.props {
        if prop.name == "key" || prop.name == "children" {
            continue;
        }
        let content = prop.name == tag.content_field;
        let optional = !prop.required || (content && tag.content != Content::None);
        property(out, prop, optional, "    ");
    }
    let children: Option<&str> = match tag.content {
        Content::Children => Some("Children"),
        Content::Child => Some("JSX.Element"),
        Content::TextArg | Content::TextField => {
            if tag.name == "Text" || tag.name == "Button" {
                Some("InlineChildren")
            } else {
                Some("TextChildren")
            }
        }
        Content::None => None,
    };
    if let Some(children) = children {
        out.push_str(&format!("    children?: {children};\n"));
    }
    if tag.name == "Text" {
        out.push_str(
            "    italic?: boolean;\n    underline?: boolean;\n    strike?: boolean;\n    background?: Color;\n",
        );
    }
    out.push_str(&format!(
        "    style?: Partial<Omit<{}Props, \"style\" | \"key\" | \"children\">>;\n",
        tag.name
    ));
    out.push_str(&format!(
        "  }}\n  export function {}(props: {}Props",
        tag.name, tag.name
    ));
    // Required content may be supplied as a named prop or as JSX children.
    if let Some(children) = children {
        for prop in &tag.props {
            if !prop.required || prop.name != tag.content_field {
                continue;
            }
            out.push_str(&format!(" & (\n    {{ {}: ", prop.name));
            prop_type(out, prop, "    ");
            out.push_str(&format!(" }} | {{ children: {children} }}\n  )"));
        }
    }
    out.push_str("): JSX.Element;\n\n");
}

fn property(out: &mut String, prop: &Prop, optional: bool, indent: &str) {
    let question = if optional { "?" } else { "" };
    out.push_str(&format!("{indent}{}{question}: ", prop.name));
    prop_type(out, prop, indent);
    out.push_str(";\n");
}

fn prop_type(out: &mut String, prop: &Prop, indent: &str) {
    let scalar: Option<&str> = match prop.kind {
        Kind::Number | Kind::Integer | Kind::Flex => Some("number"),
        Kind::Boolean => Some("boolean"),
        Kind::String => Some("string"),
        Kind::Color => Some("Color"),
        Kind::Edges => Some("Edges"),
        Kind::Dimension => Some("number | `${number}%`"),
        Kind::Action => Some("() => void"),
        Kind::BoolAction => Some("(checked: boolean) => void"),
        Kind::TextAction => Some("(value: string) => void"),
        Kind::IndexAction => Some("(index: number) => void"),
        Kind::ShortcutAction => Some("(shortcut: string) => void"),
        Kind::Node => Some("JSX.Element"),
        Kind::OptionalNode => Some("JSX.Element | null"),
        Kind::Children => Some("JSX.Element | JSX.Element[]"),
        Kind::StringList => Some("string[]"),
        Kind::Image => Some("Image | null"),
        Kind::Shortcut => Some("string | null"),
        Kind::Enumeration | Kind::Flag | Kind::StructList | Kind::Struct => None,
    };
    if let Some(scalar) = scalar {
        out.push_str(scalar);
        return;
    }
    if matches!(prop.kind, Kind::StructList | Kind::Struct) {
        out.push_str("{\n");
        let nested = format!("{indent}  ");
        for item in &prop.item_props {
            property(out, item, !item.required, &nested);
        }
        let array = if prop.kind == Kind::StructList {
            "[]"
        } else {
            ""
        };
        out.push_str(&format!("{indent}}}{array}"));
        return;
    }
    // One spelling per line also keeps large unions readable and below 120 columns.
    for (index, value) in prop.values.iter().enumerate() {
        if index != 0 {
            out.push_str(&format!("\n{indent}  | "));
        }
        out.push_str(&format!("\"{}\"", value.ts));
    }
    if prop.kind == Kind::Enumeration {
        for value in &prop.values {
            let Ok(numeric) = value.ts.parse::<u16>() else {
                continue;
            };
            out.push_str(&format!("\n{indent}  | {numeric}"));
        }
    }
    if prop.values.is_empty() {
        out.push_str("never");
    }
}
