//! Emit the generated table source (`crates/zant-tsx/src/ui_tags.rs`).
//!
//! The text is written directly, one entry per line, and `#[rustfmt::skip]` keeps
//! `cargo fmt` out of the data tables (formatting thousands of one-line entries
//! would make the diff unreadable).

use zant_tsx::tags::{Content, Kind, Prop, Sides, Skipped, Tag, Value};

use crate::table::Table;

pub fn source(table: &Table) -> String {
    let mut out = String::with_capacity(256 * 1024);
    out.push_str(HEADER);
    out.push_str(&format!(
        "//!\n//! {} tags, {} props, {} spellings, {} theme fields, {} skipped.\n",
        table.tags.len(),
        prop_count(&table.tags),
        spelling_count(&table.tags),
        table.theme.len(),
        SKIPPED.len(),
    ));
    out.push_str("use crate::tags::{Content, Kind, Prop, Sides, Skipped, Tag, Value};\n\n");
    out.push_str("/// Every supported `ui::*` builder, in table order.\n");
    out.push_str("#[rustfmt::skip]\npub fn tags() -> Vec<Tag> {\n    vec![\n");
    for tag in &table.tags {
        write_tag(&mut out, tag);
    }
    out.push_str("    ]\n}\n\n");
    out.push_str("/// Builders intentionally excluded from the generated table.\n");
    out.push_str("#[rustfmt::skip]\npub const SKIPPED: &[Skipped] = &[\n");
    for skipped in SKIPPED {
        out.push_str(&format!(
            "    Skipped {{ builder: {}, reason: {} }},\n",
            quote(skipped.builder),
            quote(skipped.reason)
        ));
    }
    out.push_str("];\n\n");
    out.push_str("/// Fields of `zant::theme::tokens::Theme`, read in TSX through `useTheme()`.\n");
    out.push_str("#[rustfmt::skip]\npub fn theme() -> Vec<Prop> {\n    vec![\n");
    for prop in &table.theme {
        out.push_str(&format!("        {},\n", prop_source(prop)));
    }
    out.push_str("    ]\n}\n");
    out
}

const HEADER: &str = "\
//! Generated by `zant-tsx-tags` from the `#[derive(TsxProps)]` metadata of
//! `crates/zant/src/ui/options.rs`; do not edit.
//!
//! One entry per `ui::*` builder.
//!
//! ```text
//! cargo run -p zant-tables --bin zant-tsx-tags -- crates/zant-tsx/src/ui_tags.rs
//! cargo run -p zant-tables --bin zant-tsx-tags -- --check crates/zant-tsx/src/ui_tags.rs
//! ```
//!
//! Tags whose builder the derive metadata does not describe are carried by
//! `crates/zant-tables/src/bin/zant-tsx-tags/pending.rs`.
";

/// The builders left out of the table, with the reason for each.
const SKIPPED: &[Skipped] = crate::table::SKIPPED;

fn write_tag(out: &mut String, tag: &Tag) {
    out.push_str(&format!(
        "        Tag {{ name: {}, builder: {}",
        quote(tag.name),
        quote(tag.builder)
    ));
    if tag.instance_id {
        out.push_str(", instance_id: true");
    }
    if tag.content != Content::None {
        out.push_str(&format!(
            ", content: Content::{content}",
            content = content(tag.content)
        ));
    }
    if !tag.content_field.is_empty() {
        out.push_str(&format!(", content_field: {}", quote(tag.content_field)));
    }
    out.push_str(", props: vec![\n");
    for prop in &tag.props {
        out.push_str(&format!("            {},\n", prop_source(prop)));
    }
    out.push_str("        ], ..Default::default() },\n");
}

fn prop_source(prop: &Prop) -> String {
    let mut out = format!(
        "Prop {{ name: {}, field: {}, kind: Kind::{}",
        quote(prop.name),
        quote(prop.field),
        kind(prop.kind)
    );
    if !prop.values.is_empty() {
        let values: Vec<String> = prop.values.iter().map(value_source).collect();
        out.push_str(&format!(", values: vec![{}]", values.join(", ")));
    }
    if prop.sides != Sides::NONE {
        out.push_str(", sides: Sides::ALL");
    }
    if !prop.percent_field.is_empty() {
        out.push_str(&format!(", percent_field: {}", quote(prop.percent_field)));
    }
    if !prop.int_type.is_empty() {
        out.push_str(&format!(", int_type: {}", quote(prop.int_type)));
    }
    if prop.required {
        out.push_str(", required: true");
    }
    if !prop.item_type.is_empty() {
        out.push_str(&format!(", item_type: {}", quote(prop.item_type)));
    }
    if !prop.item_props.is_empty() {
        let items: Vec<String> = prop.item_props.iter().map(prop_source).collect();
        out.push_str(&format!(", item_props: vec![{}]", items.join(", ")));
    }
    if !prop.parent.is_empty() {
        out.push_str(&format!(", parent: {}", quote(prop.parent)));
    }
    out.push_str(", ..Default::default() }");
    out
}

fn value_source(value: &Value) -> String {
    format!(
        "Value {{ ts: {}, rust: {} }}",
        quote(value.ts),
        quote(value.rust)
    )
}

fn content(content: Content) -> &'static str {
    match content {
        Content::Children => "Children",
        Content::TextArg => "TextArg",
        Content::TextField => "TextField",
        Content::Child => "Child",
        Content::None => "None",
    }
}

fn kind(kind: Kind) -> &'static str {
    match kind {
        Kind::Number => "Number",
        Kind::Integer => "Integer",
        Kind::Boolean => "Boolean",
        Kind::String => "String",
        Kind::Enumeration => "Enumeration",
        Kind::Color => "Color",
        Kind::Edges => "Edges",
        Kind::Dimension => "Dimension",
        Kind::Flag => "Flag",
        Kind::Flex => "Flex",
        Kind::Action => "Action",
        Kind::BoolAction => "BoolAction",
        Kind::TextAction => "TextAction",
        Kind::IndexAction => "IndexAction",
        Kind::Node => "Node",
        Kind::OptionalNode => "OptionalNode",
        Kind::Children => "Children",
        Kind::StringList => "StringList",
        Kind::StructList => "StructList",
        Kind::Image => "Image",
        Kind::Shortcut => "Shortcut",
        Kind::ShortcutAction => "ShortcutAction",
    }
}

fn prop_count(tags: &[Tag]) -> usize {
    tags.iter().map(|tag| tag.props.len()).sum()
}

fn spelling_count(tags: &[Tag]) -> usize {
    tags.iter()
        .flat_map(|tag| &tag.props)
        .map(|prop| prop.values.len())
        .sum()
}

/// Rust source for a `&'static str` literal.
fn quote(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for char in value.chars() {
        match char {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            _ => out.push(char),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn string_literals_escape_quotes_and_backslashes() {
        assert_eq!(quote("ui.@\"switch\""), "\"ui.@\\\"switch\\\"\"");
        assert_eq!(quote("a\\b"), "\"a\\\\b\"");
        assert_eq!(quote(""), "\"\"");
    }

    #[test]
    fn every_kind_has_a_rust_spelling() {
        for value in [
            Kind::Number,
            Kind::Integer,
            Kind::Boolean,
            Kind::String,
            Kind::Enumeration,
            Kind::Color,
            Kind::Edges,
            Kind::Dimension,
            Kind::Flag,
            Kind::Flex,
            Kind::Action,
            Kind::BoolAction,
            Kind::TextAction,
            Kind::IndexAction,
            Kind::Node,
            Kind::OptionalNode,
            Kind::Children,
            Kind::StringList,
            Kind::StructList,
            Kind::Image,
            Kind::Shortcut,
            Kind::ShortcutAction,
        ] {
            assert!(!kind(value).is_empty());
        }
    }
}
