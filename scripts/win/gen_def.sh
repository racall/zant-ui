#!/usr/bin/env bash
# Regenerates src/renderer/skia/zant_skia.def (exports of zant_skia.dll) from
# the C ABI headers. Run after adding a function to skia_bridge.h or pdf.h.
set -euo pipefail
cd "$(dirname "$0")/../.."
{
  echo "; Exports of zant_skia.dll: the C ABI of skia_bridge.h and pdf.h."
  echo "; Generated by scripts/win/gen_def.sh; do not edit by hand."
  echo "LIBRARY zant_skia.dll"
  echo "EXPORTS"
  grep -hoE "\bzant_[a-z0-9_]+\(" src/renderer/skia/skia_bridge.h src/platform/pdf.h | tr -d '(' | sort -u | sed 's/^/    /'
} > src/renderer/skia/zant_skia.def
