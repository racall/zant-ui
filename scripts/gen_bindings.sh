#!/usr/bin/env bash
# Regenerates the checked-in bindings of the three native C ABIs:
#
#   src/renderer/skia/skia_bridge.h -> crates/zant-sys/src/skia.rs
#   src/platform/platform.h         -> crates/zant-sys/src/platform.rs
#   src/platform/pdf.h              -> crates/zant-sys/src/pdf.rs
#
# The result is committed, so users build without libclang. CI re-runs this
# script and fails when the output differs (see .github/workflows/rust.yml).
#
# Needs the `bindgen` CLI and libclang:
#   cargo install bindgen-cli
#   macOS: libclang ships with Xcode; pass LIBCLANG_PATH if bindgen misses it.
#
# docs/rust-port/plan.md WP-0.3.
set -euo pipefail
cd "$(dirname "$0")/.."

BINDGEN="${BINDGEN:-bindgen}"
if ! command -v "$BINDGEN" >/dev/null 2>&1; then
    if [ -x .cargo-home/bin/bindgen ]; then
        BINDGEN=.cargo-home/bin/bindgen
    else
        echo "gen_bindings.sh: bindgen not found (cargo install bindgen-cli)" >&2
        exit 1
    fi
fi

# libclang discovery for macOS machines where it is not in the default search
# path (Xcode's toolchain provides it).
if [ -z "${LIBCLANG_PATH:-}" ] && [ -z "${LIBCLANG_FILE:-}" ]; then
    xcode_dir="$(xcode-select -p 2>/dev/null || true)"
    if [ -n "$xcode_dir" ] && [ -d "$xcode_dir/Toolchains/XcodeDefault.xctoolchain/usr/lib" ]; then
        export LIBCLANG_PATH="$xcode_dir/Toolchains/XcodeDefault.xctoolchain/usr/lib"
    fi
fi

# --no-layout-tests: the same generated file is compiled on macOS and Windows,
# and layout assertions are host-specific.
# -DZANT_STATIC_DATA: keeps the Windows static-link setters in the bindings on
# every host (they are only called under cfg(windows)).
generate() {
    local header="$1" out="$2"
    echo "bindgen $header -> $out"
    "$BINDGEN" "$header" --output "$out" \
        --no-layout-tests \
        --no-doc-comments \
        --formatter rustfmt \
        --allowlist-function 'zant_.*' \
        --allowlist-type '(Zant|zant).*' \
        --allowlist-var 'ZANT_.*' \
        --raw-line "// Generated by scripts/gen_bindings.sh from $header — do not edit." \
        -- -DZANT_STATIC_DATA -I.
}

generate src/renderer/skia/skia_bridge.h crates/zant-sys/src/skia.rs
generate src/platform/platform.h crates/zant-sys/src/platform.rs
generate src/platform/pdf.h crates/zant-sys/src/pdf.rs
