//! Generate editor declarations from the exact tag table used by zant-tsx.
const std = @import("std");
const tags = @import("tags.zig");
const Allocator = std.mem.Allocator;
const Output = std.ArrayList(u8);

pub fn main(init: std.process.Init) !void {
    var arena = std.heap.ArenaAllocator.init(init.gpa);
    defer arena.deinit();
    const allocator = arena.allocator();
    const args = try init.minimal.args.toSlice(allocator);
    const check = args.len > 1 and std.mem.eql(u8, args[1], "--check");
    const start: usize = if (check) 2 else 1;
    if (args.len <= start) {
        std.debug.print("usage: zant-tsx-dts [--check] <path> ...\n", .{});
        std.process.exit(2);
    }
    const output = try generate(allocator);
    for (args[start..]) |path| {
        if (check) {
            const old = std.Io.Dir.cwd().readFileAlloc(init.io, path, allocator, .limited(16 << 20)) catch |err|
                switch (err) {
                    error.FileNotFound => outdated(path),
                    else => return err,
                };
            if (!std.mem.eql(u8, old, output)) outdated(path);
        } else {
            try std.Io.Dir.cwd().writeFile(init.io, .{ .sub_path = path, .data = output });
        }
    }
}

fn outdated(path: []const u8) noreturn {
    std.debug.print("zant-tsx-dts: {s} is out of date; run `zig build tsx-dts`\n", .{path});
    std.process.exit(1);
}

fn eq(a: []const u8, b: []const u8) bool {
    return std.mem.eql(u8, a, b);
}

fn generate(allocator: Allocator) ![]const u8 {
    var out: Output = .empty;
    try out.appendSlice(allocator,
        \\// Generated by `zig build tsx-dts` from tags.zig and dts_api.d.ts. Do not edit.
        \\// Editor types describe the TSX surface; zant-tsx validates the supported TS subset.
        \\declare namespace JSX {
        \\  interface Element { readonly __zantElement: unique symbol; }
        \\  interface IntrinsicElements {}
        \\  interface IntrinsicAttributes { key?: string | number; }
        \\  interface ElementChildrenAttribute { children: {}; }
        \\}
        \\
        \\// Native Zig exports are checked by zant-tsx; the editor treats them as any.
        \\declare module "*.zig";
        \\declare module "*.png" { const bytes: Uint8Array; export default bytes; }
        \\
        \\declare module "zant" {
        \\
    );
    try out.appendSlice(allocator, @embedFile("dts_api.d.ts"));
    try out.appendSlice(allocator, "\n  export interface Theme {\n");
    for (tags.theme_fields) |prop| {
        try out.print(allocator, "    {s}: {s};\n", .{
            prop.name, if (prop.kind == .boolean) @as([]const u8, "boolean") else "number",
        });
    }
    try out.appendSlice(allocator, "  }\n\n");
    for (tags.all) |tag| try component(allocator, &out, tag);
    try out.appendSlice(allocator, "}\n");
    return out.toOwnedSlice(allocator);
}

fn component(allocator: Allocator, out: *Output, tag: tags.Tag) !void {
    try out.print(allocator, "  export interface {s}Props {{\n    key?: string | number;\n", .{tag.name});
    for (tag.props) |prop| {
        if (eq(prop.name, "key") or eq(prop.name, "children")) continue;
        const content = eq(prop.name, tag.content_field);
        const optional = !prop.required or (content and tag.content != .none);
        try property(allocator, out, prop, optional, "    ");
    }
    const children: ?[]const u8 = switch (tag.content) {
        .children => "Children",
        .child => "JSX.Element",
        .text_arg, .text_field => if (eq(tag.name, "Text") or eq(tag.name, "Button"))
            "InlineChildren"
        else
            "TextChildren",
        .none => null,
    };
    if (children) |child| try out.print(allocator, "    children?: {s};\n", .{child});
    if (eq(tag.name, "Text")) {
        try out.appendSlice(allocator,
            \\    italic?: boolean;
            \\    underline?: boolean;
            \\    strike?: boolean;
            \\    background?: Color;
            \\
        );
    }
    try out.print(allocator, "    style?: Partial<Omit<{s}Props, \"style\" | \"key\" | \"children\">>;\n", .{tag.name});
    try out.print(allocator, "  }}\n  export function {s}(props: {s}Props", .{ tag.name, tag.name });
    // Required content may be supplied as a named prop or as JSX children.
    for (tag.props) |prop| {
        if (!prop.required or !eq(prop.name, tag.content_field) or children == null) continue;
        try out.print(allocator, " & (\n    {{ {s}: ", .{prop.name});
        try propType(allocator, out, prop, "    ");
        try out.print(allocator, " }} | {{ children: {s} }}\n  )", .{children.?});
    }
    try out.appendSlice(allocator, "): JSX.Element;\n\n");
}

fn property(allocator: Allocator, out: *Output, prop: tags.Prop, optional: bool, indent: []const u8) !void {
    try out.print(allocator, "{s}{s}{s}: ", .{ indent, prop.name, if (optional) @as([]const u8, "?") else "" });
    try propType(allocator, out, prop, indent);
    try out.appendSlice(allocator, ";\n");
}

fn propType(allocator: Allocator, out: *Output, prop: tags.Prop, indent: []const u8) anyerror!void {
    const scalar: ?[]const u8 = switch (prop.kind) {
        .number, .integer, .flex => "number",
        .boolean => "boolean",
        .string => "string",
        .color => "Color",
        .edges => "Edges",
        .dimension => "number | `${number}%`",
        .action => "() => void",
        .bool_action => "(checked: boolean) => void",
        .text_action => "(value: string) => void",
        .index_action => "(index: number) => void",
        .shortcut_action => "(shortcut: string) => void",
        .node => "JSX.Element",
        .optional_node => "JSX.Element | null",
        .children => "JSX.Element | JSX.Element[]",
        .string_list => "string[]",
        .image => "Image | null",
        .shortcut => "string | null",
        .enumeration, .flag, .struct_list => null,
    };
    if (scalar) |value| return out.appendSlice(allocator, value);
    if (prop.kind == .struct_list) {
        try out.appendSlice(allocator, "{\n");
        const nested = try std.mem.concat(allocator, u8, &.{ indent, "  " });
        defer allocator.free(nested);
        for (prop.item_props) |item| try property(allocator, out, item, !item.required, nested);
        try out.print(allocator, "{s}}}[]", .{indent});
        return;
    }
    // One spelling per line also keeps large Icon unions readable and below 120 columns.
    for (prop.values, 0..) |value, i| {
        if (i != 0) try out.print(allocator, "\n{s}  | ", .{indent});
        try out.print(allocator, "\"{s}\"", .{value.ts});
    }
    if (prop.kind == .enumeration) for (prop.values) |value| {
        const numeric = std.fmt.parseInt(u16, value.ts, 10) catch continue;
        try out.print(allocator, "\n{s}  | {d}", .{ indent, numeric });
    };
    if (prop.values.len == 0) try out.appendSlice(allocator, "never");
}
