//! A TS + TSX app's generated entry (`zant-tsx --main App`): `main.zig`
//! runs the default export of `App.tsx` with `zant.tsx.app.run`, using the
//! project's `app_config.zig`: generated from `app.config.json` while
//! building (`--app-config`), or one of the inputs (older projects).
const std = @import("std");
const compile = @import("compile.zig");
const parser = @import("parser.zig");

pub const Error = error{ OutOfMemory, NoEntry, NoRoot, NameTaken };

pub fn describe(err: Error) []const u8 {
    return switch (err) {
        error.OutOfMemory => "out of memory",
        error.NoEntry => "no such .tsx file among the inputs",
        error.NoRoot => "the file has no default exported component",
        error.NameTaken => "an input is already named main.zig",
    };
}

/// The source of `main.zig` for the entry file `<name>.tsx`.
pub fn mainSource(
    arena: std.mem.Allocator,
    files: []const compile.File,
    name: []const u8,
    generated_config: bool,
) Error![]const u8 {
    var entry: ?compile.File = null;
    var config = generated_config;
    for (files) |file| {
        const output = try file.outputName(arena);
        if (std.ascii.eqlIgnoreCase(output, "main.zig")) return error.NameTaken;
        if (std.mem.eql(u8, output, "app_config.zig")) config = true;
        if (!file.isZig() and std.mem.eql(u8, std.fs.path.stem(file.path), name)) entry = file;
    }
    const file = entry orelse return error.NoEntry;
    const root = rootName(arena, file.src) orelse return error.NoRoot;
    const config_decl = if (config)
        "pub const config = @import(\"app_config.zig\");"
    else
        try std.fmt.allocPrint(arena, "pub const config = struct {{\n    pub const title: [:0]const u8 = \"{s}\";\n}};", .{root});
    return std.fmt.allocPrint(arena,
        \\//! Generated by zant-tsx: the app's entry ({s}.tsx). Do not edit.
        \\const std = @import("std");
        \\const zant = @import("zant");
        \\pub const entry = @import("{s}.zig");
        \\{s}
        \\
        \\pub fn main(init: std.process.Init) !void {{
        \\    try zant.tsx.app.run(init, entry.{s}, config);
        \\}}
        \\
    , .{ name, name, config_decl, root });
}

/// The name of the default exported component of `src`.
fn rootName(arena: std.mem.Allocator, src: []const u8) ?[]const u8 {
    var p = parser.Parser.init(arena, src);
    const module = p.parseModule() catch return null;
    for (module.functions) |top| if (top.default) return top.func.name;
    return null;
}

/// Every `.tsx` / `.zig` under `dir` (any depth, hidden entries skipped),
/// sorted so outputs don't depend on the file system's order.
pub fn collect(io: std.Io, arena: std.mem.Allocator, dir: []const u8, out: *std.ArrayList([]const u8)) !void {
    const start = out.items.len;
    try walk(io, arena, dir, out, 0);
    std.mem.sort([]const u8, out.items[start..], {}, lessThan);
}

fn lessThan(_: void, a: []const u8, b: []const u8) bool {
    return std.mem.lessThan(u8, a, b);
}

fn walk(io: std.Io, arena: std.mem.Allocator, dir_path: []const u8, out: *std.ArrayList([]const u8), depth: usize) !void {
    if (depth > 16) return;
    var dir = try std.Io.Dir.cwd().openDir(io, dir_path, .{ .iterate = true });
    defer dir.close(io);
    var it = dir.iterate();
    while (try it.next(io)) |e| {
        if (e.name.len == 0 or e.name[0] == '.') continue;
        const path = try std.fs.path.join(arena, &.{ dir_path, e.name });
        switch (e.kind) {
            .directory => try walk(io, arena, path, out, depth + 1),
            .file => if (std.mem.endsWith(u8, e.name, ".tsx") or std.mem.endsWith(u8, e.name, ".zig")) {
                try out.append(arena, path);
            },
            else => {},
        }
    }
}

test "the entry runs the default export with the project's config" {
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const app = compile.File{ .path = "src/App.tsx", .src = "export default function Clips() { return <View/>; }" };
    const config = compile.File{ .path = "src/app_config.zig", .src = "pub const title = \"x\";" };
    const with = try mainSource(a, &.{ app, config }, "App", false);
    try std.testing.expect(std.mem.indexOf(u8, with, "pub const config = @import(\"app_config.zig\");") != null);
    try std.testing.expect(std.mem.indexOf(u8, with, "zant.tsx.app.run(init, entry.Clips, config)") != null);
    const without = try mainSource(a, &.{app}, "App", false);
    try std.testing.expect(std.mem.indexOf(u8, without, "pub const title: [:0]const u8 = \"Clips\";") != null);
    try std.testing.expectError(error.NoEntry, mainSource(a, &.{app}, "Main", false));
    const main_zig = compile.File{ .path = "src/main.zig", .src = "" };
    try std.testing.expectError(error.NameTaken, mainSource(a, &.{ app, main_zig }, "App", false));
}
