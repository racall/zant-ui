//! Copy a language template, substituting project metadata only in text files.
const std = @import("std");
const cli = @import("main.zig");
const Language = @import("project.zig").Language;

pub const Options = struct {
    framework: []const u8,
    target: []const u8,
    language: Language,
    title: []const u8,
    bundle: []const u8,
    zig_name: []const u8,
    dependency: []const u8,
    hidden_titlebar: bool,
};

pub fn write(allocator: std.mem.Allocator, io: std.Io, options: Options) !void {
    const template = switch (options.language) {
        .zig => "scaffold/template",
        .ts => "scaffold/template-ts",
    };
    const source = try std.fs.path.join(allocator, &.{ options.framework, template });
    defer allocator.free(source);
    try copyTree(allocator, io, source, options.target, options, true);
    // Both languages ship the same editable icons and design rules.
    if (options.language == .ts) {
        const icons = try std.fs.path.join(allocator, &.{ options.framework, "scaffold/template/assets" });
        defer allocator.free(icons);
        const assets = try std.fs.path.join(allocator, &.{ options.target, "assets" });
        defer allocator.free(assets);
        try copyTree(allocator, io, icons, assets, options, false);
        const design = try std.fs.path.join(allocator, &.{ options.framework, "scaffold/template/DESIGN.md" });
        defer allocator.free(design);
        const dest = try std.fs.path.join(allocator, &.{ options.target, "DESIGN.md" });
        defer allocator.free(dest);
        const data = try cli.readFile(allocator, io, design);
        defer allocator.free(data);
        try cli.writeFile(allocator, io, dest, data);
    } else {
        const ignore = try std.fs.path.join(allocator, &.{ options.target, ".gitignore" });
        defer allocator.free(ignore);
        try cli.writeFile(allocator, io, ignore,
            \\# build output and caches
            \\zig-out*/
            \\.zig-cache/
            \\# Zant UI link for projects on another drive (Windows)
            \\.zant/
            \\# generated by `zant` on macOS from app.config.json
            \\Info.plist
            \\app.entitlements
            \\
        );
    }
}

fn copyTree(
    allocator: std.mem.Allocator,
    io: std.Io,
    source: []const u8,
    dest: []const u8,
    options: Options,
    substitute: bool,
) !void {
    var dir = try std.Io.Dir.cwd().openDir(io, source, .{ .iterate = true });
    defer dir.close(io);
    try std.Io.Dir.cwd().createDirPath(io, dest);
    var it = dir.iterate();
    while (try it.next(io)) |entry| {
        // app.config.json is written by create after validating all options.
        if (std.mem.eql(u8, entry.name, "app.config.json")) continue;
        const from = try std.fs.path.join(allocator, &.{ source, entry.name });
        defer allocator.free(from);
        const to = try std.fs.path.join(allocator, &.{ dest, entry.name });
        defer allocator.free(to);
        switch (entry.kind) {
            .directory => {
                const text = substitute and !std.mem.eql(u8, entry.name, "assets");
                try copyTree(allocator, io, from, to, options, text);
            },
            .file => {
                const data = try cli.readFile(allocator, io, from);
                defer allocator.free(data);
                const output = if (substitute)
                    try expand(allocator, data, options, std.mem.endsWith(u8, entry.name, ".tsx"))
                else
                    try allocator.dupe(u8, data);
                defer allocator.free(output);
                try cli.writeFile(allocator, io, to, output);
            },
            else => {},
        }
    }
}

fn expand(
    allocator: std.mem.Allocator,
    source: []const u8,
    options: Options,
    is_tsx: bool,
) ![]u8 {
    const fingerprint = (@as(u64, std.hash.Crc32.hash(options.zig_name)) << 32) | 0x9e3779b9;
    const hex = try std.fmt.allocPrint(allocator, "0x{x:0>16}", .{fingerprint});
    defer allocator.free(hex);
    const top = if (options.hidden_titlebar) "top: 56" else "top: 24";
    const pairs = [_][2][]const u8{
        .{ "__APP_NAME_SNAKE__", options.zig_name },
        .{ "__APP_FINGERPRINT__", hex },
        .{ "__ZANT_PATH__", options.dependency },
        .{ "__APP_TITLE__", options.title },
        .{ "__BUNDLE_ID__", options.bundle },
        .{ "top: 24 /* titlebar */", top },
        .{ "__TOP_PADDING__", if (options.hidden_titlebar) "56" else "24" },
    };
    var output = try allocator.dupe(u8, source);
    errdefer allocator.free(output);
    for (pairs) |pair| {
        // Titles in source must be escaped as string literals, unlike Markdown.
        const value = if (is_tsx and
            std.mem.eql(u8, pair[0], "__APP_TITLE__"))
            try cli.escapeJson(allocator, pair[1])
        else
            try allocator.dupe(u8, pair[1]);
        defer allocator.free(value);
        const replaced = try std.mem.replaceOwned(u8, allocator, output, pair[0], value);
        allocator.free(output);
        output = replaced;
    }
    return output;
}
